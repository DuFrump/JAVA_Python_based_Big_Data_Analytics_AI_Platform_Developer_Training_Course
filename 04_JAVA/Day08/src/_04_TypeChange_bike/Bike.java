package _04_TypeChange_bike;

/**
 * 안녕하세요, 두프룸프님! 이번에는 '자전거'를 예시로 상속과 다형성을 다시 한번 연습해볼 거예요.
 * 이 `Bike` 클래스는 모든 자전거의 가장 기본적인 특징과 기능을 정의하는 '부모 클래스(Superclass)'입니다.
 * 마치 모든 자전거가 '라이더 이름'과 '바퀴 수'를 가지고 있고, '정보를 보여주거나' '달릴 수 있는' 것처럼요.
 *
 * 이 클래스는 다른 종류의 자전거(예: 네발 자전거)들이 공통적으로 사용할 수 있는 기반을 제공합니다.
 * 자식 클래스들은 이 부모 클래스의 속성과 기능을 물려받아 자신만의 특별한 기능을 추가하거나,
 * 부모의 기능을 자신에게 맞게 변경(오버라이딩)할 수 있답니다.
 */
public class Bike {
    // 필드(Field): 자전거의 '속성'을 나타내는 변수들이에요.
    String riderName; // 이 자전거를 타는 사람의 이름을 저장하는 변수입니다.
    int wheel = 2;    // 자전거의 바퀴 수를 저장하는 변수입니다. 기본값은 2발 자전거로 설정되어 있어요.

    // 생성자(Constructor): `Bike` 객체를 만들 때 호출되는 특별한 메소드예요.
    // 이 생성자를 통해 자전거의 라이더 이름을 처음 만들 때 설정해 줄 수 있습니다.
    Bike(String riderName) {
        this.riderName = riderName; // 매개변수로 받은 riderName 값을 이 객체의 riderName 필드에 저장합니다.
    }

    // 메소드(Method): 자전거의 '기능'을 나타내는 동작들이에요.
    // 자전거의 기본 정보를 화면에 출력하는 메소드입니다.
    void info() {
        System.out.printf("%s의 자전거는 %d발 자전거 입니다.%n", riderName, wheel);
    }

    // 자전거가 달리는 소리를 출력하는 메소드입니다.
    void ride() {
        System.out.println("~~~씽씽~~~");
    }
}

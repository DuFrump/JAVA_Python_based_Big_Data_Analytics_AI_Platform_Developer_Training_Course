// [1] 클래스 계층 구조 정의: 동물의 소리를 흉내 내는 클래스들을 만들어볼까요?
// 먼저, 모든 동물의 부모가 될 'Animal2' 클래스를 정의해요.
// 이 클래스는 모든 동물이 공통적으로 가질 수 있는 'cry()'라는 소리 내는 메소드를 가지고 있어요.
// 여기서는 기본적으로 아무것도 하지 않지만, 자식 클래스들이 이 메소드를 자신에게 맞게 재정의(오버라이딩)할 거예요.
class Animal2 {
    void cry() { /* 기본적으로 아무 소리도 내지 않아요. */ }
}

// Animal2를 상속받는 첫 번째 자식 클래스: 돼지(Pig2)
// 돼지는 '꿀꿀~' 소리를 내죠? 부모의 cry() 메소드를 오버라이딩해서 돼지 소리를 정의해줍니다.
class Pig2 extends Animal2 {
    @Override // 이 어노테이션은 이 메소드가 부모 클래스의 메소드를 재정의한다는 것을 명시해줘요. (선택 사항이지만 권장)
    void cry() {
        System.out.println("꿀꿀~");
    }
}

// Animal2를 상속받는 두 번째 자식 클래스: 소(Cow2)
// 소는 '음메~' 소리를 내요. 마찬가지로 부모의 cry() 메소드를 오버라이딩해서 소 소리를 정의해줍니다.
class Cow2 extends Animal2 {
    @Override
    void cry() {
        System.out.println("음메~");
    }
}

// [2] Farm2 클래스: 다형성을 활용하여 동물의 소리를 내게 하는 곳
// 이 Farm2 클래스의 sound 메소드가 바로 다형성의 핵심을 보여주는 곳이에요.
class Farm2 {
    // `sound` 메소드는 `Animal2` 타입의 매개변수를 받아요.
    // 여기서 중요한 점은, 이 메소드 안에서는 `animal` 변수가 어떤 실제 객체(돼지인지, 소인지)를 참조하는지
    // 전혀 알 필요가 없다는 거예요! 단지 `Animal2` 타입이라면 `cry()` 메소드를 가지고 있다는 사실만 알면 된답니다.
    void sound(Animal2 animal) {
        // `animal.cry()`를 호출하면, 자바 런타임 시점에 실제 객체(예: Pig2 객체)에 오버라이딩된
        // `cry()` 메소드가 실행돼요. 이것이 바로 다형성(Polymorphism)의 마법이랍니다!
        animal.cry();
    }
}

public class _07_CheckByMethod {
    public static void main(String[] args) {
        // Farm2 객체를 만들어요. 이 객체를 통해 동물들의 소리를 들을 거예요.
        Farm2 farm2 = new Farm2();
        // 돼지(Pig2)와 소(Cow2) 객체를 만들어요.
        Pig2 pig2 = new Pig2();
        Cow2 cow2 = new Cow2();

        System.out.println("--- 동물의 소리 확인 (다형성 사용) ---");
        // `farm2.sound(pig2)`를 호출하면, `animal` 매개변수는 `Pig2` 객체를 참조하고,
        // `Pig2`에 오버라이딩된 `cry()` 메소드가 실행되어 "꿀꿀~"이 출력돼요.
        farm2.sound(pig2); 
        // `farm2.sound(cow2)`를 호출하면, `animal` 매개변수는 `Cow2` 객체를 참조하고,
        // `Cow2`에 오버라이딩된 `cry()` 메소드가 실행되어 "음메~"가 출력돼요.
        farm2.sound(cow2);

        System.out.println("\n----------------------------------------\n");

        // [3] `instanceof`를 사용하지 않는 다형성의 장점
        // - 코드의 유연성: 만약 새로운 동물 클래스(예: Dog2)가 추가되어도 `Farm2` 클래스의 `sound` 메소드를 수정할 필요가 없어요.
        //   새로운 동물 클래스만 Animal2를 상속받고 cry()를 오버라이딩하면 끝!
        // - 코드의 확장성: 새로운 동물을 추가하는 것이 기존 코드를 변경하지 않고도 가능하죠.
        // - 유지보수 용이성: `if-else if`와 같은 복잡한 조건문이 늘어나는 것을 방지하여 코드를 훨씬 깔끔하게 유지할 수 있답니다.
        //   이것이 바로 객체 지향 설계의 중요한 원칙 중 하나인 '개방-폐쇄 원칙(Open-Closed Principle)'과도 연결돼요.
        //   (확장에는 열려 있고, 수정에는 닫혀 있다!)
    }
}
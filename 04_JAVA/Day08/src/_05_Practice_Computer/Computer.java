package _05_Practice_Computer;

// Computer 클래스는 모든 컴퓨터의 기본적인 전원 기능을 나타내는 부모 클래스(Superclass)입니다.
public class Computer {
    // 메소드: 컴퓨터의 전원을 켜는 기능을 정의합니다.
    void powerOn() {
        System.out.println("컴퓨터 전원이 켜졌습니다!");
    }

    // 메소드: 컴퓨터의 전원을 끄는 기능을 정의합니다.
    void powerOff() {
        System.out.println("컴퓨터 전원이 꺼졌습니다!");
    }
}

package _05_Practice_Computer;

/**
 * 안녕하세요, 두프룸프님! 이번에는 '컴퓨터'를 예시로 상속과 다형성을 연습해볼 거예요.
 * 이 `Computer` 클래스는 모든 컴퓨터의 가장 기본적인 기능인 '전원 제어'를 정의하는 '부모 클래스(Superclass)'입니다.
 * 마치 모든 컴퓨터가 켜지고 꺼지는 기능을 가지고 있는 것처럼요.
 *
 * 이 클래스는 다양한 종류의 컴퓨터(예: LG 컴퓨터, Samsung 컴퓨터)들이 공통적으로 사용할 수 있는 기반을 제공합니다.
 * 자식 클래스들은 이 부모 클래스의 기능을 물려받아 자신만의 특별한 기능을 추가하거나,
 * 부모의 기능을 자신에게 맞게 변경(오버라이딩)할 수 있답니다.
 */
public class Computer {
    // 메소드(Method): 컴퓨터의 '기능'을 나타내는 동작들이에요.

    // 컴퓨터의 전원을 켜는 기능을 정의하는 메소드입니다.
    void powerOn() {
        System.out.println("컴퓨터 전원이 켜졌습니다!");
    }

    // 컴퓨터의 전원을 끄는 기능을 정의하는 메소드입니다.
    void powerOff() {
        System.out.println("컴퓨터 전원이 꺼졌습니다!");
    }
}

package _03_TypeChange_calendar;

/**
 * 안녕하세요, 두프룸프님! 이번에는 '달력'을 예시로 상속과 다형성을 다시 한번 살펴볼 거예요.
 * 이 `Calendar` 클래스는 모든 달력의 가장 기본적인 특징과 기능을 정의하는 '부모 클래스(Superclass)'입니다.
 * 마치 모든 달력이 공통적으로 '색상'과 '월 수'를 가지고 있고, '정보를 보여주거나' '벽에 걸 수 있는' 것처럼요.
 *
 * 이 클래스는 다른 종류의 달력(예: 탁상 달력)들이 공통적으로 사용할 수 있는 기반을 제공합니다.
 * 자식 클래스들은 이 부모 클래스의 속성과 기능을 물려받아 자신만의 특별한 기능을 추가할 수 있답니다.
 */
public class Calendar {
    // 필드(Field): 달력의 '속성'을 나타내는 변수들이에요.
    String color;  // 달력의 색상을 저장하는 변수입니다. (예: "빨간색", "파란색")
    int months;    // 달력의 총 월 수를 저장하는 변수입니다. (일반적으로 12월까지 있으니 12가 되겠죠?)

    // 생성자(Constructor): `Calendar` 객체를 만들 때 호출되는 특별한 메소드예요.
    // 이 생성자를 통해 달력의 색상과 월 수를 처음 만들 때 설정해 줄 수 있습니다.
    Calendar(String color, int months) {
        this.color = color;   // 매개변수로 받은 color 값을 이 객체의 color 필드에 저장합니다.
        this.months = months; // 매개변수로 받은 months 값을 이 객체의 months 필드에 저장합니다.
    }

    // 메소드(Method): 달력의 '기능'을 나타내는 동작들이에요.
    // 달력의 기본 정보를 화면에 출력하는 메소드입니다.
    void info() {
        System.out.printf("%s 달력은 %d월까지 있습니다.%n", color, months);
    }

    // 달력을 벽에 걸 수 있다는 기능을 나타내는 메소드입니다.
    // 모든 달력이 벽에 걸 수 있는 것은 아니지만, 기본적인 달력의 기능으로 정의해 보았어요.
    void hanging() {
        System.out.printf("%s 달력은 벽에 걸 수 있습니다.%n", color);
    }
}

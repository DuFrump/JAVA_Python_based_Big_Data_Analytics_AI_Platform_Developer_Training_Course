/**
 * 안녕하세요, 두프룸프님! 오늘은 Java의 아주 중요한 개념 중 하나인 '다형성(Polymorphism)'에 대해 배워볼 거예요.
 *
 * 다형성이란 무엇일까요? 쉽게 말해, '하나의 객체가 여러 가지 형태를 가질 수 있는 능력'을 의미해요.
 * 마치 한 사람이 집에서는 아들/딸, 회사에서는 직원, 친구들 앞에서는 친구 등 다양한 역할을 하는 것과 비슷하죠.
 *
 * Java에서는 주로 '상속'과 관련하여 다형성이 나타납니다.
 * 부모 클래스 타입의 참조 변수가 자식 클래스의 객체를 참조할 수 있다는 것이 핵심이에요.
 *
 * 이 예제에서는 다음을 중점적으로 살펴볼 거예요:
 * 1. 일반적인 객체 생성과 참조 방식
 * 2. 다형성을 활용한 객체 참조 (부모 타입으로 자식 객체 참조)
 * 3. 다형성 사용 시 메소드 호출과 필드 접근의 차이점
 *
 * 이 개념을 잘 이해하면 코드를 훨씬 유연하고 확장성 있게 작성할 수 있답니다!
 */

// 자, 그럼 먼저 '부모 클래스'를 정의해볼까요?
// 자, 그럼 먼저 '부모 클래스'를 정의해볼까요?
class Parent {
    // 'name'이라는 필드(속성)를 가지고 있어요. 기본값은 "부모"입니다.
    String name = "부모";

    // 'showName'이라는 메소드(기능)를 가지고 있어요. 자신의 이름을 출력하는 역할을 합니다.
    void showName() {
        System.out.println("저는 " + name + "입니다.");
    }
}

/**
 * 다음은 '자식 클래스'인 Child를 정의해볼게요.
 * Child 클래스는 Parent 클래스를 '상속(extends)'받습니다.
 * 상속을 받으면 부모 클래스의 필드와 메소드를 물려받아 사용할 수 있어요.
 */
class Child extends Parent {
    // 자식 클래스도 'name'이라는 필드를 가지고 있어요.
    // 부모 클래스에도 'name'이 있지만, 이건 별개의 필드라고 생각하면 돼요.
    // (필드 오버라이딩은 아니랍니다. 메소드 오버라이딩과 헷갈리지 마세요!)
    String name = "자식";

    /**
     * @Override 어노테이션은 이 메소드가 부모 클래스의 메소드를 '재정의(Overriding)'했다는 것을 알려줘요.
     * 부모의 showName() 메소드와 이름, 반환 타입, 매개변수가 모두 같죠?
     * 이렇게 재정의하면, 자식 객체에서 이 메소드를 호출할 때 부모의 것이 아닌 자식의 메소드가 실행됩니다.
     */
    @Override
    void showName() {
        System.out.println("저는 " + name + "입니다.");
    }
}

public class _01_TypeChange {
    public static void main(String[] args) {
        // [1] 일반적인 객체 생성과 참조
        // 여기서는 우리가 평소에 하던 대로, 각 클래스 타입에 맞는 객체를 생성하고 참조합니다.
        Parent p1 = new Parent(); // Parent 타입의 참조 변수 p1이 Parent 객체를 참조하고 있어요.
        Child c1 = new Child();   // Child 타입의 참조 변수 c1이 Child 객체를 참조하고 있네요.

        System.out.println("\n--- 일반적인 객체 참조 ---");
        p1.showName(); // Parent 객체의 showName()이 호출되어 "저는 부모입니다."가 출력됩니다.
        c1.showName(); // Child 객체의 showName()이 호출되어 "저는 자식입니다."가 출력됩니다.

        System.out.println(" ---------------------------------------- ");

        // [2] 다형성(Polymorphism)의 핵심: 부모 클래스 타입의 참조 변수가 자식 클래스 객체를 참조
        // 여기가 바로 다형성의 마법이 일어나는 부분이에요!
        // `Parent p2 = new Child();`
        // - p2는 분명히 Parent 타입의 참조 변수예요. 하지만 실제로는 Child 객체를 가리키고 있죠.
        // - 이렇게 부모 타입의 변수가 자식 객체를 참조하는 것을 '업캐스팅(Upcasting)'이라고도 부릅니다.
        //   (명시적으로 형 변환을 하지 않아도 자동으로 이루어져요. 안전한 변환이기 때문이죠.)
        // - p2를 통해서는 Parent 클래스에 정의된 멤버(필드, 메소드)만 접근할 수 있어요.
        // - 하지만! 메소드를 호출할 경우, 실제 객체(여기서는 Child)에 오버라이딩된 메소드가 호출됩니다.
        //   이것이 바로 다형성의 핵심이자, 런타임에 어떤 메소드가 실행될지 결정되는 '동적 바인딩'이랍니다.
        Parent p2 = new Child();
        // 이미 생성된 Child 객체 c1을 Parent 타입의 p3로 참조할 수도 있어요. 이것도 업캐스팅이죠!
        Parent p3 = c1;

        System.out.println("--- 다형성을 이용한 객체 참조 ---");
        p2.showName(); // p2는 Parent 타입이지만, 실제 객체는 Child이므로 Child의 showName()이 호출됩니다. 출력: "저는 자식입니다."
        p3.showName(); // p3도 Parent 타입이지만, 실제 객체는 Child이므로 Child의 showName()이 호출됩니다. 출력: "저는 자식입니다."

        // [3] 참조 변수와 실제 객체의 동일성 확인
        // p3와 c1은 서로 다른 참조 변수이지만, 실제로는 메모리 상의 '같은 Child 객체'를 가리키고 있어요.
        if (p3 == c1) {
            System.out.println("\np3와 c1은 같은 객체를 참조하고 있습니다. (주소값이 같아요!)");
        }

        // [4] 필드 접근 시 주의사항: 메소드 오버라이딩과 다릅니다!
        // 다형성에서 필드(변수)에 접근할 때는 메소드와는 다르게 동작해요.
        // 필드는 '참조 변수의 타입'에 따라 결정됩니다. 실제 객체의 타입과는 무관하죠.
        // 이것은 필드가 '오버라이딩'되는 개념이 없기 때문이에요. (메소드만 오버라이딩됩니다.)
        System.out.println("\n--- 필드 접근 시 주의사항 ---");
        System.out.println("p2.name: " + p2.name); // p2는 Parent 타입이므로 Parent의 name 필드("부모")에 접근합니다. 출력: "부모"
        System.out.println("c1.name: " + c1.name); // c1은 Child 타입이므로 Child의 name 필드("자식")에 접근합니다. 출력: "자식"

        System.out.println("\n두프룸프님, 다형성 개념이 조금 이해가 되셨나요? 이 예제를 통해 다형성의 기본 원리를 잘 파악하셨기를 바랍니다!");
    }
}

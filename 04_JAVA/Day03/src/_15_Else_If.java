// 안녕하세요, 두프룸프님!
// 이 파일은 `if-else if-else` 조건문을 사용하여 여러 개의 조건을 순차적으로 검사하고,
// 그에 따라 다른 코드를 실행하는 방법을 배우는 예제입니다.
// 특히, 조건의 '순서'가 얼마나 중요한지 이해하는 것이 핵심이에요!

import java.util.Scanner; // 사용자 입력을 위한 Scanner 클래스를 불러옵니다.

public class _15_Else_If { // 클래스 선언
    public static void main(String[] args) { // main 메서드: 프로그램 시작점

        // [1] 숫자 비교 예제: `if-else if-else`의 기본 동작 이해
        int fav_num = 10; // 좋아하는 숫자 변수를 10으로 설정

        // 첫 번째 조건: fav_num이 10보다 작은가?
        // (10 < 10) -> 거짓(false)
        if(fav_num < 10) {
            System.out.println("좋아하는 숫자가 10보다 작군요.");
        } 
        // 두 번째 조건: 첫 번째 조건이 거짓일 때만 이 조건을 검사합니다.
        // fav_num이 10보다 큰가?
        // (10 > 10) -> 거짓(false)
        else if(fav_num > 10) {
            System.out.println("좋아하는 숫자가 10보다 크군요.");
        } 
        // 마지막 `else`: 위의 모든 `if`와 `else if` 조건이 거짓일 때 실행됩니다.
        // 즉, fav_num이 10보다 작지도 않고, 크지도 않을 때 (fav_num이 10일 때) 실행됩니다.
        else {
            System.out.println("좋아하는 숫자가 10이군요."); // 출력: 좋아하는 숫자가 10이군요.
        }

        System.out.println("\n----------------------------------------\n"); // 구분선

        // [2] 나이대별 분류 예제: 조건 순서의 중요성
        // 이 예제에서는 사용자로부터 나이를 입력받아 해당 나이대가 어디에 속하는지 분류합니다.
        // 여기서 중요한 것은 `if-else if` 문의 '조건 순서'입니다.
        // 조건을 잘못된 순서로 배치하면 예상치 못한 결과가 나올 수 있어요!

        Scanner sc = new Scanner(System.in);
        System.out.print("나이를 입력하세요 : ");
        int age = sc.nextInt(); // 사용자로부터 나이를 입력받습니다.

        // ★★★ 조건 순서의 중요성 ★★★
        // 만약 `age > 6` (어린이) 조건을 `age > 19` (성인) 조건보다 먼저 검사한다면,
        // 20세인 사람도 `age > 6` 조건에 해당하여 '어린이'로 분류될 수 있습니다.
        // 따라서, 더 '구체적인' 또는 '범위가 좁은' 조건을 먼저 검사하거나,
        // 아니면 '범위가 넓은' 조건부터 '좁은' 조건으로 순차적으로 검사하되, 조건식을 잘 설계해야 합니다.
        // 여기서는 '가장 큰 나이대'부터 '가장 작은 나이대'로 내려오면서 검사하는 방식을 사용합니다.

        // 조건 1: 나이가 19세 초과인가? (성인)
        // 예를 들어 age가 25라면, 25 > 19는 참이므로 이 블록이 실행되고 나머지는 건너뜁니다.
        if(age > 19) {
            System.out.println("성인입니다.");
        } 
        // 조건 2: 첫 번째 조건이 거짓일 때만 검사합니다.
        // 나이가 13세 초과인가? (즉, 19세 이하이면서 13세 초과인 경우 = 청소년)
        // 예를 들어 age가 15라면, 첫 번째 조건은 거짓이고, 15 > 13은 참이므로 이 블록이 실행됩니다.
        else if(age > 13) {
            System.out.println("청소년입니다.");
        } 
        // 조건 3: 두 번째 조건이 거짓일 때만 검사합니다.
        // 나이가 6세 초과인가? (즉, 13세 이하이면서 6세 초과인 경우 = 어린이)
        // 예를 들어 age가 8이라면, 첫 번째, 두 번째 조건은 거짓이고, 8 > 6은 참이므로 이 블록이 실행됩니다.
        else if(age > 6) {
            System.out.println("어린이입니다.");
        } 
        // 마지막 `else`: 위의 모든 조건이 거짓일 때 실행됩니다.
        // 즉, 나이가 6세 이하인 경우 (유아)
        else {
            System.out.println("유아입니다.");
        }

        sc.close(); // Scanner 자원 해제

        // 이 예제를 통해 `else if`를 사용하여 여러 조건을 효율적으로 처리하는 방법과
        // 조건의 순서가 결과에 미치는 영향을 잘 이해하셨기를 바랍니다!
    }
}

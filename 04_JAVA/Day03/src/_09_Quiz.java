// 안녕하세요, 두프룸프님!
// 이 파일은 앞서 배운 문자열 처리(특히 substring)와 조건 연산자(삼항 연산자)를 활용하여
// 주민등록번호에서 생일과 성별 정보를 추출하는 퀴즈 예제입니다.
// 실생활 데이터에서 필요한 정보를 뽑아내는 연습이라고 생각하면 돼요!

public class _09_Quiz { // 클래스 선언
    public static void main(String[] args) { // main 메서드: 프로그램 시작점

        // 예시 주민등록번호를 하나 준비합니다.
        // 주민등록번호는 '생년월일 6자리 - 성별 및 출생지 등 7자리'로 구성됩니다.
        // 예: 901232-1234567 (90년 12월 32일생, 성별 코드 1)
        String id_number = "901232-1234567"; // 예시 주민등록번호

        // [1] 생일 추출하기
        // 주민등록번호에서 생일은 '월'과 '일'을 의미하는 부분이에요.
        // 예시 "901232-1234567"에서 '1232'가 월일입니다.
        // 이 부분은 전체 문자열에서 인덱스 2부터 인덱스 6 '전'까지에 해당합니다.
        // (기억하세요! 인덱스는 0부터 시작하고, substring의 두 번째 인자는 '미만'입니다.)
        // id_number.substring(2, 6)의 의미:
        // - 2: 시작 인덱스 (0부터 세어서 세 번째 글자부터 시작)
        // - 6: 끝 인덱스 (여섯 번째 글자까지, 즉 일곱 번째 글자 직전까지)
        String birth = id_number.substring(2, 6); // "901232"에서 "1232" (월일) 추출

        // [2] 성별 추출 및 판별하기
        // 주민등록번호에서 성별을 나타내는 숫자는 하이픈(-) 바로 뒤에 오는 한 자리 숫자입니다.
        // 예시 "901232-1234567"에서 '1'이 성별 코드입니다.
        // 이 부분은 전체 문자열에서 인덱스 7에 해당합니다.
        // substring(startIndex, endIndex)를 사용하면 편리해요. (인덱스 7부터 8 전까지)
        String gender_code = id_number.substring(7, 8); // "1234567"에서 "1" (성별 코드) 추출

        // 이제 추출한 성별 코드를 가지고 성별이 '남자'인지 '여자'인지 판별해볼까요?
        // 주민등록번호 성별 코드는 다음과 같아요:
        // 1 또는 3: 남자 (1900년대생 남자, 2000년대생 남자)
        // 2 또는 4: 여자 (1900년대생 여자, 2000년대생 여자)
        // 여기서는 간단하게 '1'이면 남자, 그 외에는 여자로 판별해봅시다.

        // 조건 연산자(삼항 연산자)를 사용합니다.
        // (조건식) ? (참일 때의 값) : (거짓일 때의 값);
        // ★ 중요! 문자열 비교는 반드시 `equals()` 메소드를 사용해야 합니다.
        // `==` 연산자는 문자열의 '내용'이 아니라 '메모리 주소'를 비교한다는 것을 잊지 마세요!
        String gender = (gender_code.equals("1")) ? "남자" : "여자";

        // [3] 결과 출력
        // printf를 사용하여 추출한 생일과 성별 정보를 보기 좋게 출력합니다.
        // %s는 문자열을 위한 형식 지정자입니다.
        // %n은 줄바꿈을 위한 형식 지정자입니다.
        System.out.printf("생일은 %s이고, 성별은 %s입니다.%n", birth, gender);
    }
}

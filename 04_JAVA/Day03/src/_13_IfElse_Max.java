// 안녕하세요, 두프룸프님!
// 이 파일은 `if-else` 조건문을 활용하여 두 개의 숫자 중에서 '더 큰 값(최대값)'을 찾아내는 예제입니다.
// 아주 간단하지만, 조건문을 사용하여 특정 상황에 따라 다른 결과를 얻는 기본적인 로직을 이해하는 데 도움이 될 거예요.

public class _13_IfElse_Max { // 클래스 선언
    public static void main(String[] args) { // main 메서드: 프로그램 시작점

        int a = 4;  // 첫 번째 숫자 변수 'a'에 4를 할당합니다.
        int b = 10; // 두 번째 숫자 변수 'b'에 10을 할당합니다.
        int max = 0; // 두 숫자 중 더 큰 값을 저장할 변수 'max'를 선언하고 0으로 초기화합니다.
                     // (어떤 값이 들어올지 모르니 일단 0으로 시작하는 것이 일반적입니다.)

        // `if-else` 문을 사용하여 a와 b를 비교하고, 더 큰 값을 max 변수에 저장합니다.
        // 조건식: a > b (a가 b보다 큰가?)
        // 현재: 4 > 10 -> 결과는 거짓(false)입니다.
        if(a > b) { // 만약 a가 b보다 크다면 (조건식이 참이라면)...
            // 이 블록이 실행됩니다. 즉, a가 더 크므로 max에 a의 값을 저장합니다.
            max = a;
        } else { // 그렇지 않다면 (조건식이 거짓이라면)...
            // 이 블록이 실행됩니다. 즉, a가 b보다 작거나 같으므로 max에 b의 값을 저장합니다.
            max = b;
        }

        // 최종적으로 찾아낸 최대값을 화면에 출력합니다.
        // printf를 사용하여 변수들의 값을 형식에 맞춰 출력합니다.
        System.out.printf("%d와 %d 중에 큰 수는 %d입니다.%n", a, b, max); // 출력: 4와 10 중에 큰 수는 10입니다.

        // ★ 참고: 이 최대값 찾기 로직은 앞서 배운 '삼항 연산자'로도 아주 간결하게 표현할 수 있습니다.
        // int max_ternary = (a > b) ? a : b;
        // System.out.println("삼항 연산자 사용: " + max_ternary);
        // 삼항 연산자는 코드를 한 줄로 줄일 수 있다는 장점이 있지만,
        // 복잡한 조건에서는 `if-else`가 더 읽기 쉬울 수 있습니다. 상황에 맞게 선택해서 사용하세요!
    }
}

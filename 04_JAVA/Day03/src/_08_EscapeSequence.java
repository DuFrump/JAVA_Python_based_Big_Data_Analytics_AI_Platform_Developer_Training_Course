// 안녕하세요, 두프룸프님!
// 이 파일은 자바에서 '이스케이프 시퀀스(Escape Sequence)'에 대해 배우는 예제입니다.
// 이스케이프 시퀀스는 문자열 안에 특별한 의미를 가진 문자들을 표현하거나,
// 줄 바꿈, 탭 간격 띄우기 등 특수한 기능을 수행할 때 사용하는 '역슬래시(\) + 문자' 조합이에요.
// 마치 문자열에 숨겨진 '특수 명령어'를 넣는 것과 같다고 생각하면 됩니다!

public class _08_EscapeSequence { // 클래스 선언
    public static void main(String[] args) { // main 메서드: 프로그램 시작점

        // [1] \n : 줄 바꿈 (New Line)
        // 문자열을 출력하다가 \n을 만나면, 그 다음 내용은 새로운 줄에서 시작됩니다.
        System.out.println("--- \n (줄바꿈) ---");
        System.out.println("날씨가");
        System.out.println("정말");
        System.out.println("좋아요.");

        // 위 세 줄의 출력을 \n을 사용하여 한 줄의 코드만으로 표현할 수 있습니다.
        System.out.println("날씨가\n정말\n좋아요.");

        System.out.println("\n----------------------------------------\n"); // 구분선

        // [2] \t : 탭 (Tab)
        // 문자열 사이에 일정한 간격(탭)을 띄울 때 사용합니다.
        // 표 형태의 데이터를 정렬할 때 유용하게 쓰여요.
        System.out.println("--- \t (탭) ---");
        System.out.println("빽다방 2000원");
        System.out.println("스타벅스 5000원");

        // \t를 사용하여 가격 정보를 깔끔하게 정렬된 형태로 출력할 수 있습니다.
        System.out.println("빽다방\t2000원");
        System.out.println("스타벅스\t5000원");

        System.out.println("\n----------------------------------------\n"); // 구분선

        // [3] \\ : 역슬래시 (Backslash)
        // 역슬래시(\)는 이스케이프 시퀀스의 시작을 알리는 특별한 문자입니다.
        // 만약 문자열 안에 역슬래시 자체를 표현하고 싶다면, 역슬래시를 두 번(\\) 써야 합니다.
        // 첫 번째 역슬래시가 '나 이스케이프 시퀀스야!'라고 알려주고, 두 번째 역슬래시가 '내가 출력될 문자야!'라고 알려주는 셈이죠.
        System.out.println("--- \\ (역슬래시) ---");
        // 파일 경로 등을 출력할 때 역슬래시가 자주 사용되므로 이스케이프 시퀀스를 활용합니다.
        System.out.println("C:\\Program Files\\Java");

        System.out.println("\n----------------------------------------\n"); // 구분선

        // [4] \" : 큰따옴표 (Double Quote)
        // 문자열은 큰따옴표("")로 시작하고 끝납니다.
        // 만약 문자열 안에 큰따옴표를 직접 넣고 싶다면, \"처럼 역슬래시와 함께 사용해야 합니다.
        // 그렇지 않으면 자바는 문자열이 거기서 끝났다고 오해할 수 있어요.
        System.out.println("--- \" (큰따옴표) ---");
        System.out.println("그녀가 나한테 말했다. \"배고프니?\"");

        System.out.println("\n----------------------------------------\n"); // 구분선

        // [5] \' : 작은따옴표 (Single Quote)
        // 작은따옴표('')는 주로 하나의 문자(char)를 표현할 때 사용합니다.
        // 문자열(String) 안에 작은따옴표를 넣을 때는 보통 이스케이프 시퀀스 없이도 잘 작동하지만,
        // 명확성을 위해 \'를 사용할 수도 있습니다. 특히 char 타입에서는 작은따옴표를 이스케이프할 필요가 없어요.
        System.out.println("--- \' (작은따옴표) ---");
        System.out.println("너의 속마음이 들리는 거 같아. \'아.. 배고파..\'");
    }
}

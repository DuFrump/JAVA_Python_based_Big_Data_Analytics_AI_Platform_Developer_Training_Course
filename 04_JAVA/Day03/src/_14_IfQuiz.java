// 안녕하세요, 두프룸프님!
// 이 파일은 `if-else` 조건문을 활용하여 사용자로부터 나이를 입력받고,
// 그 나이에 따라 '성인'인지 '미성년자'인지 판별하여 출력하는 간단한 퀴즈 예제입니다.
// 조건문의 가장 기본적인 활용법을 다시 한번 복습하고 다지는 시간이라고 생각하면 돼요!

import java.util.Scanner; // 사용자 입력을 위한 Scanner 클래스를 불러옵니다.

public class _14_IfQuiz { // 클래스 선언
    public static void main(String[] args) { // main 메서드: 프로그램 시작점

        // 1. Scanner 객체 생성: 사용자 입력을 받기 위한 준비입니다.
        Scanner sc = new Scanner(System.in);

        // 2. 사용자에게 나이 입력 요청 메시지 출력
        System.out.print("나이를 입력하세요 : ");

        // 3. 사용자로부터 정수형 나이를 입력받아 `age` 변수에 저장
        int age = sc.nextInt();

        // 4. `if-else` 조건문을 사용하여 나이에 따라 다른 메시지 출력
        // 조건식: `age >= 19` (나이가 19세 이상인가?)
        // 대한민국에서는 보통 만 19세부터 성인으로 간주합니다.
        if (age >= 19) { // 만약 나이가 19세 이상이라면 (조건식이 참이라면)...
            // 이 블록이 실행됩니다. 즉, 성인인 경우입니다.
            System.out.println("성인입니다.");
        } else { // 그렇지 않다면 (조건식이 거짓이라면)...
            // 이 블록이 실행됩니다. 즉, 19세 미만인 미성년자인 경우입니다.
            System.out.println("미성년자입니다.");
        }

        // 5. Scanner 자원 해제
        // 사용이 끝난 Scanner 객체는 시스템 자원 관리를 위해 반드시 닫아주는 것이 좋습니다.
        sc.close();

        // 이 퀴즈는 `if-else`의 가장 기본적인 형태를 이해하는 데 중점을 둡니다.
        // 실제 프로그램에서는 더 복잡한 조건이나 여러 단계의 판별이 필요할 수 있지만,
        // 모든 복잡한 로직도 결국 이런 기본적인 조건문들의 조합으로 이루어진다는 것을 기억하세요!
    }
}

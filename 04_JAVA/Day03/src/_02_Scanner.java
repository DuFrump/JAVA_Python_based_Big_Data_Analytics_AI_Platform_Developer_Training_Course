// 안녕하세요, 두프룸프님!
// 이 파일은 자바에서 사용자로부터 다양한 형태의 정보를 입력받는 방법을 배우는 곳이에요.
// 특히, 숫자를 입력받은 후에 문장(줄)을 입력받을 때 주의해야 할 점을 집중적으로 살펴볼 거예요.

import java.util.Scanner; // 사용자 입력을 위한 Scanner 클래스를 불러옵니다.

public class _02_Scanner { // 파일 이름과 동일한 클래스 선언
    public static void main(String[] args) { // 프로그램의 시작점인 main 메서드

        // 사용자로부터 입력받을 정보들을 저장할 변수들을 미리 선언해둡니다.
        String name;    // 이름을 저장할 문자열(String) 변수
        double height;  // 키를 저장할 실수(double) 변수
        int age;        // 나이를 저장할 정수(int) 변수
        String address; // 주소지를 저장할 문자열(String) 변수

        // Scanner 객체 생성: 키보드(System.in)로부터 입력을 받을 준비를 합니다.
        Scanner sc = new Scanner(System.in);

        // 1. 이름 입력받기 (sc.next() 사용)
        System.out.print("이름이 어떻게 되시나요? : ");
        // sc.next(): 사용자가 입력한 내용 중 '공백(띄어쓰기, 탭, 엔터) 전까지의 한 단어'만 읽어옵니다.
        // 예를 들어 "홍 길동"이라고 입력하면 "홍"만 읽어와요.
        name = sc.next();

        // 2. 키 입력받기 (sc.nextDouble() 사용)
        System.out.print("%n키가 어떻게 되시나요? (예: 175.5) : ");
        // sc.nextDouble(): 사용자가 입력한 내용을 실수(double) 형태로 읽어옵니다.
        height = sc.nextDouble();

        // 3. 나이 입력받기 (sc.nextInt() 사용)
        System.out.print("%n나이가 어떻게 되시나요? : ");
        // sc.nextInt(): 사용자가 입력한 내용을 정수(int) 형태로 읽어옵니다.
        age = sc.nextInt();

        // 4. 주소지 입력받기 (sc.nextLine() 사용 시 아주 중요한 주의사항!)
        System.out.print("%n주소지는 어떻게 되시나요? (띄어쓰기 포함 가능) : ");

        // ★★★★★ 여기서부터 중요해요! ★★★★★
        // sc.nextInt()나 sc.nextDouble() 같은 메서드들은 숫자만 읽고, 사용자가 숫자를 입력한 후 누른 '엔터(줄바꿈 문자 \n)'는
        // 입력 버퍼(임시 저장 공간)에 그대로 남겨둡니다.
        // 예를 들어, 나이로 '20'을 입력하고 엔터를 치면, 버퍼에는 '\n'이 남아있게 돼요.

        // 이 상태에서 sc.nextLine()을 바로 호출하면, nextLine()은 버퍼에 남아있던 그 '\n'을
        // 마치 사용자가 입력한 것처럼 읽어버리고, 더 이상 입력을 기다리지 않고 바로 종료해버립니다.
        // 그래서 우리가 주소지를 입력할 기회도 없이 프로그램이 다음으로 넘어가 버리는 문제가 발생해요!

        // 이 문제를 해결하려면, 남아있는 '\n'을 미리 제거해줘야 합니다.
        sc.nextLine(); // 버퍼에 남아있는 '엔터(\n)'를 읽어서 버려주는 역할을 합니다. (일명 '엔터 소비')

        // 이제 버퍼가 깨끗해졌으니, sc.nextLine()이 정상적으로 한 줄 전체를 입력받을 수 있게 됩니다.
        // sc.nextLine(): 사용자가 엔터를 칠 때까지 입력한 '한 줄 전체'를 읽어옵니다. 공백도 포함해서요!
        address = sc.nextLine(); // 이제 정상적으로 주소지 전체를 입력받을 수 있습니다.

        // 입력받은 모든 정보들을 보기 좋게 출력합니다.
        // %s: 문자열, %d: 정수, %.1f: 소수점 첫째 자리까지 표시하는 실수
        // \n: 줄바꿈 문자 (printf에서는 %n을 쓰는 것이 더 권장되지만, \n도 사용 가능합니다.)
        System.out.printf("%n%n%n당신의 이름은 %s이고, 나이는 %d이군요. 또한 키는 %.1fcm, 현재 거주지는 %s입니다.\n", name, age, height, address);

        // Scanner 사용이 끝났으면, 자원을 효율적으로 사용하기 위해 닫아주는 것이 좋습니다.
        sc.close();
    }
}

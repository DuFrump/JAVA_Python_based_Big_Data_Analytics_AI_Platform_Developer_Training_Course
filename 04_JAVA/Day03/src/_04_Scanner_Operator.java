// 안녕하세요, 두프룸프님!
// 이 파일은 우리가 앞서 배운 '사용자 입력(Scanner)'과 '삼항 연산자(Operator)'를 함께 활용하는 예제입니다.
// 사용자로부터 두 개의 숫자를 입력받아서, 그 숫자들의 크기를 삼항 연산자로 비교해볼 거예요.

import java.util.Scanner; // 사용자 입력을 위한 Scanner 클래스를 불러옵니다.

public class _04_Scanner_Operator { // 클래스 선언
    public static void main(String[] args) { // main 메서드: 프로그램 시작점

        // 1. Scanner 객체 생성: 사용자 입력을 받을 준비를 합니다.
        // 키보드(System.in)로부터 입력을 받을 거예요.
        Scanner sc = new Scanner(System.in);

        // 2. 첫 번째 숫자 입력받기
        System.out.print("숫자 a를 입력해주세요 : ");
        // sc.nextInt(): 사용자가 입력한 정수 값을 읽어와서 변수 'a'에 저장합니다.
        int a = sc.nextInt();

        // 3. 두 번째 숫자 입력받기
        System.out.print("숫자 b를 입력해주세요 : ");
        // sc.nextInt(): 사용자가 입력한 정수 값을 읽어와서 변수 'b'에 저장합니다.
        int b = sc.nextInt();

        // 4. 중첩된 삼항 연산자를 사용하여 a와 b의 크기 비교
        // 삼항 연산자의 구조: (조건식) ? (참일 때의 값) : (거짓일 때의 값);
        // 여기서는 거짓일 때의 값 자리에 또 다른 삼항 연산자가 들어간 '중첩' 형태입니다.

        // result = (a >= b) ? ((a == b) ? "a와 b는 같다." : "a는 b보다 크다.") : "a가 b보다 작다.";

        // 이 코드를 단계별로 분석해볼까요?
        // ① 가장 바깥쪽 조건식 평가: (a >= b)
        //    - 만약 'a가 b보다 크거나 같다면' (true), 물음표(?) 바로 뒤의 괄호 안 내용이 실행됩니다.
        //      즉, ((a == b) ? "a와 b는 같다." : "a는 b보다 크다.") 이 부분이 다음 단계로 넘어갑니다.
        //    - 만약 'a가 b보다 작다면' (false), 콜론(:) 뒤의 값인 "a가 b보다 작다."가 최종 결과가 됩니다.

        // ② (a >= b)가 true일 때 실행되는 안쪽 삼항 연산자 평가: (a == b) ? "a와 b는 같다." : "a는 b보다 크다."
        //    - 만약 'a와 b가 같다면' (true), "a와 b는 같다."가 최종 결과가 됩니다.
        //    - 만약 'a와 b가 같지 않다면' (false), (a >= b)가 true였으므로 'a는 b보다 크다'는 의미가 됩니다.
        //      따라서 "a는 b보다 크다."가 최종 결과가 됩니다.

        String result = (a >= b) ? ((a == b) ? "a와 b는 같다." : "a는 b보다 크다.") : "a가 b보다 작다.";

        // 5. 비교 결과 출력
        System.out.println(result);

        // 6. Scanner 자원 해제
        // 사용이 끝난 Scanner 객체는 반드시 닫아주어 시스템 자원을 효율적으로 관리해야 합니다.
        sc.close();
    }
}


/**
 * 안녕하세요, 두프룸프님! 이번에는 'Detectable'이라는 간단한 '인터페이스(Interface)'를 살펴볼 거예요.
 * 이 인터페이스는 '감지' 기능을 가진 모든 객체가 공통적으로 가져야 할 '규약'을 정의합니다.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **인터페이스의 정의**: `interface` 키워드를 사용하여 선언합니다.
 *     - 이 인터페이스는 어떤 종류의 감지기든 '감지하는 기능'을 제공해야 한다는 것을 명시합니다.
 *
 * 2.  **추상 메소드**: 인터페이스에 선언된 모든 메소드는 기본적으로 `public abstract`입니다.
 *     - `void detect();`와 같이 선언만 있고 구현(몸체)이 없는 메소드예요.
 *     - 이 인터페이스를 구현하는 모든 클래스(예: `AccidentDetector`, `FireDetector`)는
 *       `detect()` 메소드를 반드시 오버라이딩하여 구현해야 합니다.
 *       이는 감지 기능을 가진 모든 객체가 '감지하는' 기능을 제공해야 한다는 '규약'을 강제하는 것입니다.
 *
 * 이 'Detectable' 인터페이스는 다양한 종류의 감지기(사고 감지기, 화재 감지기 등)들이
 * 공통된 '감지' 기능을 가질 수 있도록 하는 추상적인 틀을 제공합니다.
 * 함께 코드를 보면서 인터페이스의 단순하지만 강력한 역할을 이해해 봅시다!
 */

package _06_Detector;

// Detectable 인터페이스는 감지 기능이 있는 모든 객체가 가져야 할 공통적인 기능을 정의합니다.
// 이 인터페이스를 구현하는 클래스는 `detect()` 메소드를 반드시 구현해야 합니다.
public interface Detectable {
    /**
     * 추상 메소드: `detect()`
     * 무언가를 감지하는 기능을 정의합니다.
     * 이 메소드는 구현부가 없으며, 이 인터페이스를 구현하는 모든 클래스에서
     * 각자의 방식으로 `detect()` 기능을 구현해야 합니다.
     * 예를 들어, 사고 감지기는 사고를 감지하고, 화재 감지기는 화재를 감지하는 식으로 구현될 수 있습니다.
     */
    void detect();
}
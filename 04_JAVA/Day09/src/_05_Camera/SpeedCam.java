package _05_Camera;

// SpeedCam 클래스는 Camera 추상 클래스를 상속받는 자식 클래스입니다.
// 'extends Camera'를 통해 Camera 클래스의 모든 멤버를 물려받습니다.
// Camera 클래스의 추상 메소드인 `showMainFeature()`를 반드시 구현해야만 객체 생성이 가능해집니다.
public class SpeedCam extends Camera {
    /**
     * 추상 메소드 구현: `showMainFeature()`
     * 부모 클래스(Camera)의 추상 메소드를 오버라이딩하여 과속 단속 카메라의 주요 기능을 출력합니다.
     * `@Override` 어노테이션은 이 메소드가 부모의 메소드를 재정의한다는 것을 명시합니다.
     */
    @Override
    public void showMainFeature() {
        System.out.println("속도 측정, 번호 인식"); // 과속 단속 카메라의 주요 기능은 속도 측정 및 번호 인식입니다.
    }

    /**
     * [참고] 일반 메소드의 상속:
     * Camera 클래스에 정의된 일반 메소드(`showFeature()`)는
     * SpeedCam 클래스에서 별도로 오버라이딩하지 않아도 그대로 물려받아 사용할 수 있습니다.
     * 예를 들어, `SpeedCam sc = new SpeedCam();` 객체를 생성한 후,
     * `sc.showFeature();`를 호출하면 Camera 클래스에 구현된 내용이 실행됩니다.
     * 물론, 필요하다면 이 메소드도 `@Override`하여 SpeedCam만의 특별한 동작을 정의할 수 있습니다.
     */
}
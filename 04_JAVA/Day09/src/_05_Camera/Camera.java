/**
 * 안녕하세요, 두프룸프님! 이번에는 'Camera'라는 '추상 클래스(Abstract Class)'를 자세히 살펴볼 거예요.
 * 이 클래스는 모든 카메라가 공통적으로 가져야 할 기능들을 정의하면서도,
 * 각 카메라 모델마다 다르게 구현될 수 있는 부분은 '추상 메소드'로 남겨두는 방법을 보여줍니다.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **추상 클래스 (Abstract Class)의 목적**: 
 *     - `abstract` 키워드로 선언되며, 직접 객체를 생성할 수 없어요.
 *     - 자식 클래스들에게 공통된 틀을 제공하고, 특정 메소드를 반드시 구현하도록 강제하는 역할을 합니다.
 *     - 예를 들어, 모든 카메라는 '사진 촬영', '동영상 녹화' 같은 기본 기능이 있지만,
 *       '주요 기능'은 카메라의 종류(공장 카메라, 과속 단속 카메라)에 따라 다를 수 있겠죠?
 *       이런 경우에 추상 클래스가 유용합니다.
 *
 * 2.  **추상 메소드 (Abstract Method)의 활용**: 
 *     - 선언만 있고 구현(메소드 몸체 `{}`)이 없는 메소드예요. (예: `public abstract void showMainFeature();`)
 *     - 추상 메소드를 하나라도 포함하는 클래스는 반드시 추상 클래스로 선언되어야 합니다.
 *     - 이 메소드는 이 클래스를 상속받는 모든 자식 클래스에서 '반드시' 오버라이딩하여 구현해야 합니다.
 *       만약 구현하지 않으면, 그 자식 클래스도 추상 클래스가 되어야 해요.
 *
 * 3.  **일반 메소드와 추상 메소드의 조합**: 
 *     - 추상 클래스는 추상 메소드뿐만 아니라 일반 메소드(구현부가 있는 메소드)도 가질 수 있어요.
 *     - `showFeature()`와 같이 모든 카메라가 공통적으로 가지는 기능은 일반 메소드로 구현하고,
 *       `showMainFeature()`와 같이 각 카메라마다 다르게 구현되어야 하는 핵심 기능은 추상 메소드로 정의합니다.
 *
 * 이 'Camera' 클래스는 객체 지향 설계에서 '추상화(Abstraction)' 개념을 어떻게 적용하는지 보여주는 좋은 예시입니다.
 * 함께 코드를 보면서 추상 클래스의 유연성과 강제성을 이해해 봅시다!
 */

package _05_Camera;

// Camera 클래스는 추상 클래스(Abstract Class)입니다.
// `abstract` 키워드가 붙어 있어 이 클래스 자체로는 객체를 직접 생성할 수 없습니다.
// 모든 카메라의 공통적인 기능을 정의하며, 특정 기능(`showMainFeature()`)은 자식 클래스에서 반드시 구현하도록 강제합니다.
public abstract class Camera {
    /**
     * 일반 메소드: 카메라의 공통적인 기능을 보여줍니다.
     * 이 메소드는 구현부가 있으므로 추상 메소드가 아닙니다.
     * 자식 클래스에서 별도로 오버라이딩하지 않으면 이 구현이 그대로 사용됩니다.
     */
    public void showFeature() {
        System.out.println("사진 촬영, 동영상 녹화");
    }

    /**
     * 추상 메소드: `showMainFeature()`
     * 이 메소드는 선언만 있고 구현(메소드 몸체 `{}`)이 없는 메소드입니다.
     * `abstract` 키워드를 사용하며, 반드시 추상 클래스 내에 선언되어야 합니다.
     * 이 메소드는 Camera 클래스를 상속받는 모든 자식 클래스(예: FactoryCam, SpeedCam)에서
     * '반드시' 오버라이딩하여 각 카메라의 주요 기능을 구현해야 합니다.
     * 예를 들어, 공장 카메라는 '화재 감지'가 주요 기능일 수 있고, 과속 단속 카메라는 '속도 측정'이 주요 기능일 수 있습니다.
     */
    public abstract void showMainFeature();
}
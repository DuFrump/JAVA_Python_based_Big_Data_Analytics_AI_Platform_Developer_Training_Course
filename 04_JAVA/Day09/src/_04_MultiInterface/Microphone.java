/**
 * 안녕하세요, 두프룸프님! 이번에는 'Microphone'이라는 간단한 '인터페이스(Interface)'를 살펴볼 거예요.
 * 인터페이스는 클래스가 구현해야 할 메소드들의 '규약'을 정의하는 역할을 합니다.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **인터페이스의 정의**: `interface` 키워드를 사용하여 선언합니다.
 *     - 이 인터페이스는 마이크가 가져야 할 기본적인 기능, 즉 '노래하는 기능'을 정의합니다.
 *
 * 2.  **추상 메소드**: 인터페이스에 선언된 모든 메소드는 기본적으로 `public abstract`입니다.
 *     - `void sing();`와 같이 선언만 있고 구현(몸체)이 없는 메소드예요.
 *     - 이 인터페이스를 구현하는 모든 클래스(예: `BlueToothMIC`, `TJmic`)는
 *       `sing()` 메소드를 반드시 오버라이딩하여 구현해야 합니다.
 *       이는 마이크 기능을 가진 모든 객체가 '노래하는' 기능을 제공해야 한다는 '규약'을 강제하는 것입니다.
 *
 * 이 'Microphone' 인터페이스는 특정 장치(마이크)가 어떤 '행동'을 할 수 있어야 하는지 정의하는
 * 가장 기본적인 형태의 인터페이스 예시입니다.
 * 함께 코드를 보면서 인터페이스의 단순하지만 강력한 역할을 이해해 봅시다!
 */

package _04_MultiInterface;

// Microphone 인터페이스는 마이크가 가져야 할 기본적인 기능을 정의합니다.
// 이 인터페이스를 구현하는 클래스는 `sing()` 메소드를 반드시 구현해야 합니다.
public interface Microphone {
    /**
     * 추상 메소드: `sing()`
     * 마이크를 통해 노래하는 기능을 정의합니다.
     * 이 메소드는 구현부가 없으며, 이 인터페이스를 구현하는 모든 클래스에서
     * 각자의 방식으로 `sing()` 기능을 구현해야 합니다.
     */
    void sing();
}
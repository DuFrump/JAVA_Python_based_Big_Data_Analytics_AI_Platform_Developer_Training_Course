/**
 * 안녕하세요, 두프룸프님! 이번에는 'BlueToothMIC' 클래스를 통해
 * 자바에서 '인터페이스의 다중 구현(Multiple Interface Implementation)'이 어떻게 가능한지 배워볼 거예요.
 * 자바는 클래스의 다중 상속은 허용하지 않지만, 인터페이스는 여러 개를 동시에 구현할 수 있습니다.
 * 이는 하나의 클래스가 여러 가지 '역할'을 수행할 수 있도록 해주는 강력한 기능입니다.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **인터페이스의 다중 구현**: 
 *     - `implements Speaker, Microphone`과 같이 쉼표(`,`)로 구분하여 여러 인터페이스를 동시에 구현할 수 있어요.
 *     - 이는 'BlueToothMIC'가 'Speaker'의 역할도 하고, 'Microphone'의 역할도 한다는 의미입니다.
 *
 * 2.  **모든 추상 메소드 구현의 의무**: 
 *     - 다중 구현을 할 경우, 해당 클래스는 구현하는 모든 인터페이스에 정의된 추상 메소드들을
 *       '모두' 오버라이딩하여 구현해야 합니다.
 *     - 만약 하나라도 빠뜨리면 컴파일 에러가 발생해요.
 *
 * 3.  **다중 상속의 한계와 인터페이스의 대안**: 
 *     - 자바는 클래스의 다중 상속을 허용하지 않습니다. (예: `class Child extends Parent1, Parent2`는 불가능)
 *       이는 '다이아몬드 문제(Diamond Problem)'와 같은 복잡성을 피하기 위함입니다.
 *     - 하지만 인터페이스의 다중 구현을 통해 하나의 클래스가 여러 타입의 '행동'을 가질 수 있도록 하여,
 *       다중 상속의 장점을 어느 정도 가져오면서도 단점을 피할 수 있습니다.
 *
 * 이 'BlueToothMIC' 클래스는 블루투스 마이크가 스피커 역할(반주 재생)과 마이크 역할(노래 부르기)을
 * 동시에 수행하는 것을 코드로 보여주는 좋은 예시입니다.
 * 함께 코드를 보면서 인터페이스의 다중 구현이 어떻게 동작하는지 이해해 봅시다!
 */

package _04_MultiInterface;

// BlueToothMIC 클래스는 Speaker 인터페이스와 Microphone 인터페이스를 동시에 구현(implements)합니다.
// 자바는 클래스의 다중 상속은 지원하지 않지만, 인터페이스의 다중 구현은 지원합니다.
// 따라서 이 클래스는 두 인터페이스에 정의된 모든 추상 메소드를 반드시 오버라이딩하여 구현해야 합니다.
public class BlueToothMIC implements Speaker, Microphone {
    /**
     * [1] Microphone 인터페이스의 `sing()` 메소드 구현
     * `@Override` 어노테이션은 이 메소드가 Microphone 인터페이스의 `sing()` 메소드를 구현한다는 것을 명시합니다.
     * 마이크에 대고 노래를 부르는 동작을 정의합니다.
     */
    @Override
    public void sing() {
        System.out.println("마이크에 대고 노래를 부릅니다.");
    }

    /**
     * [2] Speaker 인터페이스의 `music()` 메소드 구현
     * `@Override` 어노테이션은 이 메소드가 Speaker 인터페이스의 `music()` 메소드를 구현한다는 것을 명시합니다.
     * 마이크에 장착된 스피커로 반주가 나오는 동작을 정의합니다.
     */
    @Override
    public void music() {
        System.out.println("마이크에 장착된 스피커로 반주가 나옵니다.");
    }
}
/**
 * 안녕하세요, 두프룸프님! 이번에는 'Speaker'라는 간단한 '인터페이스(Interface)'를 살펴볼 거예요.
 * 'Microphone' 인터페이스와 매우 유사한 구조를 가지고 있으니, 비교하면서 이해하면 더욱 좋습니다.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **인터페이스의 정의 복습**: `interface` 키워드를 사용하여 선언합니다.
 *     - 이 인터페이스는 스피커가 가져야 할 기본적인 기능, 즉 '음악을 재생하는 기능'을 정의합니다.
 *
 * 2.  **추상 메소드 복습**: 인터페이스에 선언된 모든 메소드는 기본적으로 `public abstract`입니다.
 *     - `void music();`와 같이 선언만 있고 구현(몸체)이 없는 메소드예요.
 *     - 이 인터페이스를 구현하는 모든 클래스(예: `BlueToothMIC`, `TJmic`)는
 *       `music()` 메소드를 반드시 오버라이딩하여 구현해야 합니다.
 *       이는 스피커 기능을 가진 모든 객체가 '음악을 재생하는' 기능을 제공해야 한다는 '규약'을 강제하는 것입니다.
 *
 * 이 'Speaker' 인터페이스는 특정 장치(스피커)가 어떤 '행동'을 할 수 있어야 하는지 정의하는
 * 기본적인 형태의 인터페이스 예시입니다.
 * 함께 코드를 보면서 인터페이스의 단순하지만 강력한 역할을 다시 한번 확인해 봅시다!
 */

package _04_MultiInterface;

// Speaker 인터페이스는 스피커가 가져야 할 기본적인 기능을 정의합니다.
// 이 인터페이스를 구현하는 클래스는 `music()` 메소드를 반드시 구현해야 합니다.
public interface Speaker {
    /**
     * 추상 메소드: `music()`
     * 스피커를 통해 음악을 재생하는 기능을 정의합니다.
     * 이 메소드는 구현부가 없으며, 이 인터페이스를 구현하는 모든 클래스에서
     * 각자의 방식으로 `music()` 기능을 구현해야 합니다.
     */
    void music();
}
/**
 * 안녕하세요, 두프룸프님! 이번에는 'Reportable'이라는 간단한 '인터페이스(Interface)'를 살펴볼 거예요.
 * 이 인터페이스는 '보고' 기능을 가진 모든 객체가 공통적으로 가져야 할 '규약'을 정의합니다.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **인터페이스의 정의**: `interface` 키워드를 사용하여 선언합니다.
 *     - 이 인터페이스는 어떤 종류의 보고자든 '보고하는 기능'을 제공해야 한다는 것을 명시합니다.
 *
 * 2.  **추상 메소드**: 인터페이스에 선언된 모든 메소드는 기본적으로 `public abstract`입니다.
 *     - `void report();`와 같이 선언만 있고 구현(몸체)이 없는 메소드예요.
 *     - 이 인터페이스를 구현하는 모든 클래스(예: `NormalReporter`, `VideoReporter`)는
 *       `report()` 메소드를 반드시 오버라이딩하여 구현해야 합니다.
 *       이는 보고 기능을 가진 모든 객체가 '보고하는' 기능을 제공해야 한다는 '규약'을 강제하는 것입니다.
 *
 * 이 'Reportable' 인터페이스는 다양한 종류의 보고자(일반 보고자, 영상 보고자 등)들이
 * 공통된 '보고' 기능을 가질 수 있도록 하는 추상적인 틀을 제공합니다.
 * 함께 코드를 보면서 인터페이스의 단순하지만 강력한 역할을 이해해 봅시다!
 */

package _07_Reporter;

// Reportable 인터페이스는 보고 기능을 가진 모든 객체가 가져야 할 공통적인 기능을 정의합니다.
// 이 인터페이스를 구현하는 클래스는 `report()` 메소드를 반드시 구현해야 합니다.
public interface Reportable {
    /**
     * 추상 메소드: `report()`
     * 보고하는 기능을 정의합니다.
     * 이 메소드는 구현부가 없으며, 이 인터페이스를 구현하는 모든 클래스에서
     * 각자의 방식으로 `report()` 기능을 구현해야 합니다.
     * 예를 들어, 일반 보고자는 텍스트로 보고하고, 영상 보고자는 영상으로 보고하는 식으로 구현될 수 있습니다.
     */
    void report();
}
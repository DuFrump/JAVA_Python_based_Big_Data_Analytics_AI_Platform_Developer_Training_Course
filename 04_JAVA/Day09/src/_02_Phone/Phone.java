/**
 * 안녕하세요, 두프룸프님! 이번에는 'Phone'이라는 추상 클래스를 자세히 살펴볼 거예요.
 * 이 클래스는 모든 휴대폰이 공통적으로 가져야 할 기능들을 정의하면서도,
 * 각 휴대폰 모델마다 다르게 구현될 수 있는 부분은 '추상 메소드'로 남겨두는 방법을 보여줍니다.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **추상 클래스 (Abstract Class)의 목적**: 
 *     - 'abstract' 키워드로 선언되며, 직접 객체를 생성할 수 없어요.
 *     - 자식 클래스들에게 공통된 틀을 제공하고, 특정 메소드를 반드시 구현하도록 강제하는 역할을 합니다.
 *     - 예를 들어, 모든 휴대폰은 '전원 켜기', '전원 끄기' 기능이 있지만,
 *       '시작 로고'는 제조사마다 다를 수 있겠죠? 이런 경우에 추상 클래스가 유용합니다.
 *
 * 2.  **추상 메소드 (Abstract Method)의 활용**: 
 *     - 선언만 있고 구현(메소드 몸체 `{}`)이 없는 메소드예요. (예: `abstract void openingLogo();`)
 *     - 추상 메소드를 하나라도 포함하는 클래스는 반드시 추상 클래스로 선언되어야 합니다.
 *     - 이 메소드는 이 클래스를 상속받는 모든 자식 클래스에서 '반드시' 오버라이딩하여 구현해야 합니다.
 *       만약 구현하지 않으면, 그 자식 클래스도 추상 클래스가 되어야 해요.
 *
 * 3.  **일반 메소드와 추상 메소드의 조합**: 
 *     - 추상 클래스는 추상 메소드뿐만 아니라 일반 메소드(구현부가 있는 메소드)도 가질 수 있어요.
 *     - 일반 메소드 안에서 추상 메소드를 호출할 수도 있습니다.
 *       이 경우, 실제 실행 시에는 자식 클래스에서 구현된 추상 메소드가 호출됩니다.
 *
 * 이 'Phone' 클래스는 객체 지향 설계에서 '추상화(Abstraction)' 개념을 어떻게 적용하는지 보여주는 좋은 예시입니다.
 * 함께 코드를 보면서 추상 클래스의 유연성과 강제성을 이해해 봅시다!
 */

package _02_Phone;

// Phone 클래스는 추상 클래스(Abstract Class)입니다.
// 'abstract' 키워드가 붙어 있어 이 클래스 자체로는 객체를 직접 생성할 수 없습니다.
// 모든 휴대폰의 공통적인 기능을 정의하며, 특정 기능(openingLogo)은 자식 클래스에서 반드시 구현하도록 강제합니다.
public abstract class Phone {
    /**
     * 추상 메소드(Abstract Method): `openingLogo()`
     * - 이 메소드는 선언만 있고 구현(메소드 몸체 `{}`)이 없는 메소드입니다.
     * - `abstract` 키워드를 사용하며, 반드시 추상 클래스 내에 선언되어야 합니다.
     * - 이 메소드는 Phone 클래스를 상속받는 모든 자식 클래스(예: PineapplePhone)에서
     *   '반드시' 오버라이딩하여 각자의 방식으로 구현해야 합니다.
     * - 만약 자식 클래스에서 이 메소드를 구현하지 않으면, 그 자식 클래스도 추상 클래스로 선언해야 합니다.
     */
    abstract void openingLogo();

    /**
     * 일반 메소드: 핸드폰 전원을 켜는 기능입니다.
     * 이 메소드는 구현부가 있으므로 추상 메소드가 아닙니다.
     * 자식 클래스에서 별도로 오버라이딩하지 않으면 이 구현이 그대로 사용됩니다.
     */
    void powerOn() {
        // [참고] 만약 전원을 켤 때 로고가 먼저 보이게 하고 싶다면,
        // 여기서 `openingLogo()`를 호출할 수 있습니다.
        // `openingLogo()`를 여기서 호출하면, 실제 실행 시에는 자식 클래스에서 구현된 메소드가 호출됩니다.
        // 예를 들어, PineapplePhone 객체에서 powerOn()을 호출하면 PineapplePhone의 openingLogo()가 실행됩니다.
        // openingLogo(); // 현재는 주석 처리되어 있습니다.
        System.out.println("핸드폰이 켜집니다.");
    }

    /**
     * 일반 메소드: 핸드폰 전원을 끄는 기능입니다.
     * 이 메소드 역시 구현부가 있으므로 추상 메소드가 아닙니다.
     */
    void powerOff() {
        System.out.println("핸드폰이 꺼집니다.");
    }
}
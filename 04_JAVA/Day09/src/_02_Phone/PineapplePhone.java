/**
 * 안녕하세요, 두프룸프님! 이번에는 'PineapplePhone' 클래스를 통해
 * 'Phone' 추상 클래스에 정의된 '추상 메소드'를 어떻게 '구현(implement)'하는지 배워볼 거예요.
 * 추상 클래스가 제시한 '틀'을 자식 클래스가 어떻게 '완성'하는지 이해하는 데 핵심적인 부분입니다.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **추상 메소드 구현의 의무**: 
 *     - 부모 클래스(Phone)에 `abstract void openingLogo();`와 같이 추상 메소드가 선언되어 있다면,
 *       이 추상 클래스를 상속받는 모든 자식 클래스(PineapplePhone)는
 *       이 `openingLogo()` 메소드를 반드시 오버라이딩하여 구현해야 합니다.
 *     - 만약 구현하지 않으면, 자식 클래스도 추상 클래스로 선언해야 하는 컴파일 에러가 발생해요.
 *
 * 2.  **`@Override` 어노테이션**: 
 *     - 이 어노테이션은 메소드가 부모 클래스의 메소드를 '재정의(오버라이딩)'한다는 것을 컴파일러에게 알려주는 역할을 해요.
 *     - 필수는 아니지만, 사용하면 오타나 잘못된 메소드 시그니처로 인한 오류를 컴파일 시점에 잡아낼 수 있어 매우 유용합니다.
 *       (예: 부모 메소드 이름이 `openingLogo`인데 자식에서 `openningLogo`로 오타를 내면 에러 발생!)
 *
 * 3.  **일반 메소드의 상속**: 
 *     - 부모 클래스(Phone)에 구현부가 있는 일반 메소드(예: `powerOn()`, `powerOff()`)는
 *       자식 클래스에서 별도로 오버라이딩하지 않아도 그대로 물려받아 사용할 수 있습니다.
 *
 * 이 클래스는 추상 클래스의 설계 의도를 자식 클래스가 어떻게 충실히 따르는지 보여주는 좋은 예시입니다.
 * 함께 코드를 보면서 추상 메소드 구현의 중요성을 확실히 이해해 봅시다!
 */

package _02_Phone;

// PineapplePhone 클래스는 Phone 추상 클래스를 상속받는 자식 클래스입니다.
// 'extends Phone'을 통해 Phone 클래스의 모든 멤버를 물려받습니다.
// Phone 클래스의 추상 메소드인 `openingLogo()`를 반드시 구현해야만 객체 생성이 가능해집니다.
public class PineapplePhone extends Phone {
    /**
     * 추상 메소드 구현: `openingLogo()`
     * 부모 클래스(Phone)의 추상 메소드를 오버라이딩하여 파인애플 폰만의 로고를 출력합니다.
     * `@Override` 어노테이션은 이 메소드가 부모의 메소드를 재정의한다는 것을 명시적으로 나타냅니다.
     */
    @Override
    void openingLogo() {
        System.out.println("★★★"); // 파인애플 폰의 로고를 출력합니다.
    }

    /**
     * [참고] 일반 메소드의 상속:
     * Phone 클래스에 정의된 일반 메소드들(예: `powerOn()`, `powerOff()`)은
     * PineapplePhone 클래스에서 별도로 오버라이딩하지 않아도 그대로 물려받아 사용할 수 있습니다.
     * 예를 들어, `PineapplePhone pp = new PineapplePhone();` 객체를 생성한 후,
     * `pp.powerOn();`이나 `pp.powerOff();`를 호출하면 Phone 클래스에 구현된 내용이 실행됩니다.
     * 물론, 필요하다면 이 메소드들도 `@Override`하여 PineapplePhone만의 특별한 동작을 정의할 수 있습니다.
     */
}
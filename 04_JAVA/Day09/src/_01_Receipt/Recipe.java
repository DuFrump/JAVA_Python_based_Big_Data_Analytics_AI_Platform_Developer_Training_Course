/**
 * 안녕하세요, 두프룸프님! 이번에는 'Recipe'라는 추상 클래스를 자세히 살펴볼 거예요.
 * 추상 클래스는 객체 지향 프로그래밍에서 매우 중요한 개념 중 하나입니다.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **추상 클래스 (Abstract Class) 정의**: 'abstract' 키워드로 선언된 클래스예요.
 *     - 이 클래스는 '미완성된 설계도'와 같아서, 그 자체로는 직접 객체를 만들 수 없어요.
 *       (예: `new Recipe()`는 불가능!)
 *     - 하지만 자식 클래스들에게 공통적인 속성(필드)과 기능(메소드)을 물려주고,
 *       특정 메소드를 반드시 구현하도록 강제하는 역할을 합니다.
 *
 * 2.  **추상 메소드 (Abstract Method)의 역할**: 
 *     - 추상 메소드는 선언만 있고 구현(메소드 몸체 `{}`)이 없는 메소드예요.
 *       (예: `public abstract void prepare();`)
 *     - 추상 메소드를 하나라도 포함하는 클래스는 반드시 추상 클래스로 선언되어야 합니다.
 *     - 추상 메소드의 목적은 자식 클래스들이 이 메소드를 각자의 방식대로 '반드시' 구현하도록 강제하는 것입니다.
 *       이는 프로그램의 일관성을 유지하고, 개발자가 중요한 기능을 빠뜨리지 않도록 도와줍니다.
 *
 * 3.  **추상 클래스의 생성자**: 추상 클래스도 생성자를 가질 수 있어요.
 *     - 직접 객체를 만들 수는 없지만, 자식 클래스가 객체를 생성할 때 `super()`를 통해
 *       부모(추상 클래스)의 생성자를 호출하여 부모의 필드를 초기화할 수 있습니다.
 *
 * 이 'Recipe' 클래스는 모든 레시피의 기본적인 틀을 제공하면서도,
 * 각 레시피(파스타, 스테이크 등)마다 다르게 구현되어야 할 부분을 자식 클래스에 위임하는 방법을 보여줍니다.
 * 함께 코드를 보면서 추상 클래스의 유용성을 이해해 봅시다!
 */

package _01_Receipt;

// Recipe 클래스는 추상 클래스(Abstract Class)입니다.
// 'abstract' 키워드가 붙어 있어 이 클래스 자체로는 객체를 직접 생성할 수 없습니다.
// 이 클래스는 모든 레시피의 공통적인 속성(예: 셰프 이름)과 기능을 정의하며,
// 자식 클래스에서 반드시 구현해야 할 추상 메소드를 포함할 수 있습니다.
public abstract class Recipe {
    // 필드: 이 레시피를 만든 셰프의 이름을 저장하는 변수입니다.
    String chef;

    /**
     * Recipe 클래스의 생성자입니다.
     * 추상 클래스도 생성자를 가질 수 있으며, 이 생성자는 자식 클래스에서 `super()`를 통해 호출됩니다.
     * 자식 클래스가 객체를 생성할 때, 부모 클래스의 필드를 초기화하는 데 사용됩니다.
     * @param chef 레시피를 만든 셰프의 이름
     */
    Recipe(String chef) {
        this.chef = chef;
    }

    /**
     * 일반 메소드: 현재 레시피의 정보를 출력합니다.
     * 이 메소드는 추상 메소드가 아니므로, 자식 클래스에서 오버라이딩하지 않아도 사용할 수 있습니다.
     * 물론, 필요하다면 자식 클래스에서 오버라이딩하여 내용을 변경할 수도 있습니다.
     */
    void info() {
        System.out.printf("이 레시피는 %s 셰프님의 레시피입니다.%n", chef);
    }

    /**
     * [참고] 추상 메소드 (Abstract Method) 예시:
     * 만약 여기에 'public abstract void prepare();'와 같은 추상 메소드를 추가한다면,
     * 이 메소드는 선언만 있고 구현(메소드 몸체 `{}`)이 없는 상태가 됩니다.
     * 
     * 예시:
     * public abstract void prepare(); // 재료 준비 과정을 정의하는 추상 메소드
     * public abstract void cook();    // 요리 과정을 정의하는 추상 메소드
     *
     * 추상 메소드를 하나라도 포함하는 클래스는 반드시 'abstract' 키워드를 붙여 추상 클래스로 선언되어야 합니다.
     * 그리고 이 'Recipe' 클래스를 상속받는 모든 자식 클래스(예: PastaRecipe, StakeRecipe)는
     * 이 추상 메소드들을 반드시 오버라이딩하여 각자의 방식으로 구현해야 합니다.
     * 이는 자식 클래스들이 특정 기능을 빠뜨리지 않고 구현하도록 강제하는 중요한 메커니즘입니다.
     */
}
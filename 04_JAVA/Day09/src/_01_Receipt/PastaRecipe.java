/**
 * 안녕하세요, 두프룸프님! 이번에는 'PastaRecipe' 클래스를 통해
 * 추상 클래스인 'Recipe'를 어떻게 상속받아 구현하는지 자세히 살펴볼 거예요.
 *
 * <오늘 배울 핵심 개념>
 * 1.  **상속 (Inheritance) 복습**: 'extends' 키워드를 사용하여 부모 클래스의 속성과 메소드를 물려받는 것을 다시 한번 확인합니다.
 *     'PastaRecipe'는 'Recipe'의 자식 클래스가 되어 'Recipe'가 가진 모든 것을 사용할 수 있게 됩니다.
 *
 * 2.  **'super()' 키워드**: 자식 클래스의 생성자에서 부모 클래스의 생성자를 호출할 때 사용해요.
 *     부모 클래스의 초기화 작업을 자식 클래스에서 수행할 수 있도록 해줍니다.
 *     여기서는 'Recipe' 클래스의 `chef` 필드를 초기화하는 데 사용됩니다.
 *
 * 3.  **추상 메소드 구현의 의무**: 만약 부모 클래스인 'Recipe'에 추상 메소드가 있었다면,
 *     'PastaRecipe' 클래스는 그 추상 메소드를 반드시 구현(오버라이딩)해야 합니다.
 *     이 예제에서는 'Recipe' 클래스에 추상 메소드가 없지만, 만약 있었다면 어떻게 해야 하는지 설명해 드릴게요.
 *
 * 이 클래스는 파스타 레시피만의 고유한 기능(`makePasta()`)을 추가하면서도,
 * 부모 클래스의 공통된 구조를 따르는 방법을 보여줍니다.
 * 함께 코드를 보면서 상속의 실제 적용 사례를 익혀봅시다!
 */

package _01_Receipt;

// PastaRecipe 클래스는 Recipe 추상 클래스를 상속받는 자식 클래스입니다.
// 'extends Recipe'를 통해 Recipe 클래스의 모든 멤버(필드, 메소드)를 물려받습니다.
// 이 클래스는 파스타 레시피만의 특성과 조리법을 정의합니다.
public class PastaRecipe extends Recipe {
    /**
     * PastaRecipe 클래스의 생성자입니다.
     * 새로운 PastaRecipe 객체를 생성할 때 호출됩니다.
     * @param chef 레시피를 만드는 요리사의 이름
     */
    PastaRecipe(String chef){
        // 'super(chef)'는 부모 클래스(Recipe)의 생성자를 호출하는 코드입니다.
        // 이를 통해 부모 클래스에 정의된 'chef' 필드를 초기화합니다.
        // 자식 클래스의 생성자에서 부모 클래스의 생성자를 호출할 때는 항상 첫 줄에 와야 합니다.
        super(chef);
    }

    /**
     * 파스타를 만드는 과정을 정의하는 메소드입니다.
     * 이 메소드는 PastaRecipe 클래스에만 있는 고유한 기능입니다.
     */
    void makePasta() {
        System.out.println("파스타를 맛있게 만듭니다.");
    }

    /**
     * [참고] 추상 메소드 구현에 대한 설명:
     * 만약 부모 클래스인 'Recipe'에 'public abstract void prepare();'와 같은 추상 메소드가 있었다면,
     * 'PastaRecipe' 클래스는 이 'prepare()' 메소드를 반드시 '오버라이딩(Overriding)'하여 구현해야 합니다.
     * 예를 들어:
     * @Override
     * public void prepare() {
     *     System.out.println("파스타 재료를 준비합니다.");
     * }
     * 만약 추상 메소드를 구현하지 않으면, 'PastaRecipe' 클래스도 추상 클래스로 선언해야 하는 컴파일 에러가 발생합니다.
     * 이는 추상 클래스가 자식 클래스에게 특정 메소드를 반드시 구현하도록 강제하는 중요한 역할입니다.
     */
}
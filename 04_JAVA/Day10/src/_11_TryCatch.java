/**
 * 두프룸프님을 위한 주석 가이드:
 * 이 코드는 자바의 '예외 처리(Exception Handling)'에서 가장 기본이 되는
 * 'try-catch' 문을 보여줍니다.
 *
 * [try-catch란?]
 * 프로그램 실행 중 예상치 못한 문제(예외)가 발생했을 때,
 * 프로그램이 갑자기 멈추는 것을 방지하고, 개발자가 미리 정해둔 방식으로
 * 문제를 처리하여 프로그램이 안정적으로 계속 실행되도록 돕는 문법입니다.
 *
 * [비유]
 * 'try' 블록은 '위험한 작업 구역'입니다. 예를 들어, 요리사가 뜨거운 오븐에 손을 넣는 것과 같습니다.
 * 'catch' 블록은 '안전망' 또는 '응급처치실'입니다. 만약 오븐에 손을 데면(예외 발생),
 * 즉시 응급처치실로 가서 치료를 받는(예외 처리) 것과 같습니다.
 * try-catch를 사용하면, 손을 데더라도(예외 발생) 요리(프로그램) 전체가 중단되지 않고
 * 계속 진행될 수 있습니다.
 */
public class _11_TryCatch {
    public static void main(String[] args) {
        int result = 0;

        // 1. 'try' 블록: 예외가 발생할 가능성이 있는 코드를 이 안에 작성합니다.
        //    자바는 이 블록 안에서 예외가 발생하는지 '시도(try)'해 봅니다.
        try {
            // 이 부분에서 'ArithmeticException' (산술 예외)가 발생합니다.
            // 어떤 수를 0으로 나누는 것은 수학적으로 불가능하며, 자바에서는 이를 예외로 처리합니다.
            result = 10 / 0; // 여기서 예외 발생!
            // 예외가 발생하면, 이 줄 아래의 try 블록 내 코드는 실행되지 않고
            // 즉시 해당 예외를 처리할 수 있는 'catch' 블록으로 제어가 넘어갑니다.
            System.out.printf("나누기 결과 : %d%n", result); // 이 코드는 실행되지 않습니다.
        }
        // 2. 'catch' 블록: 'try' 블록에서 특정 예외가 발생했을 때, 그 예외를 '잡아서(catch)' 처리합니다.
        //    괄호 안에는 어떤 종류의 예외를 잡을지 명시합니다. 여기서는 ArithmeticException을 잡습니다.
        catch (ArithmeticException e) {
            // 예외가 발생했을 때 실행될 코드입니다.
            System.out.println("오류 발생: 0으로 나누기는 불가능합니다.");
            // 예외 객체 'e'를 통해 예외에 대한 더 자세한 정보를 얻을 수도 있습니다.
            // System.out.println("예외 메시지: " + e.getMessage());
            // e.printStackTrace(); // 예외 발생 경로를 출력 (디버깅 시 유용)
        }

        // 3. try-catch 블록 이후의 코드:
        //    예외가 발생했더라도 catch 블록에서 처리되었기 때문에,
        //    프로그램은 비정상 종료되지 않고 이어서 실행됩니다.
        System.out.println("프로그램이 안정적으로 종료됩니다.");
    }
}
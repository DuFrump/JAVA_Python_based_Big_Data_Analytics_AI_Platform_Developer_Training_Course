/**
 * 두프룸프님을 위한 주석 가이드:
 * 이 코드는 '익명 내부 클래스(Anonymous Inner Class)'가 '인터페이스'를
 * 구현(implement)하는 가장 기본적인 형태를 보여줍니다.
 *
 * [익명 클래스와 인터페이스]
 * 익명 클래스는 이름이 없기 때문에, 주로 인터페이스를 즉석에서 구현하거나
 * 추상 클래스를 상속받아 메소드를 바로 재정의할 때 사용됩니다.
 * 딱 한 번만 사용할 기능이 필요할 때 코드를 간결하게 작성할 수 있는 강력한 방법입니다.
 *
 * [비유]
 * 'Greeting' 인터페이스는 "인사하는 방법"에 대한 '규칙' 또는 '설계도'입니다.
 * 익명 클래스는 이 규칙에 따라 "안녕하세요!"라고 인사하는 '일회용 로봇'을
 * 그 자리에서 바로 만들어서 사용하는 것과 같습니다.
 * 이 로봇은 다른 곳에서는 재사용되지 않고, 이 인사 한 번을 위해 태어났다가 사라집니다.
 */

// [1. 인터페이스 정의]
// 'Greeting'이라는 인터페이스를 정의합니다.
// 이 인터페이스는 'sayHello()'라는 추상 메소드를 가지고 있습니다.
// 즉, 이 인터페이스를 구현하는 모든 클래스는 반드시 'sayHello()' 메소드를
// 자신만의 방식으로 구현해야 한다는 '규칙'을 정해놓은 것입니다.
interface Greeting {
    void sayHello(); // 인사를 하는 기능을 정의 (구현 내용은 없음)
}

public class AnonymousClassEX {
    public static void main(String[] args) {
        // [2. 익명 클래스를 사용하여 인터페이스 구현 및 객체 생성]
        // 'new Greeting() { ... };' 이 부분이 바로 익명 클래스입니다.
        // 'Greeting' 인터페이스를 '이름 없이' 즉석에서 구현하고, 동시에 그 구현체의 객체를 생성합니다.
        // 이 객체는 'greeting' 변수에 할당됩니다.
        Greeting greeting = new Greeting() {
            // @Override 어노테이션은 부모 클래스나 인터페이스의 메소드를 재정의(Override)했음을 나타냅니다.
            // 여기서는 Greeting 인터페이스의 sayHello() 메소드를 구현합니다.
            @Override
            public void sayHello() {
                System.out.println("안녕하세요!"); // sayHello() 메소드의 실제 동작을 정의
            }
        };

        // [3. 익명 클래스 객체의 메소드 실행]
        // 생성된 익명 클래스 객체 'greeting'의 sayHello() 메소드를 호출합니다.
        // 이 호출은 위에서 정의된 "안녕하세요!"를 출력하는 코드를 실행하게 됩니다.
        greeting.sayHello();
    }
}
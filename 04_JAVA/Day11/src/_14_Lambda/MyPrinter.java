package _14_Lambda;

/**
 * Java 선생님:
 * 두프룸프님, 이제부터 람다(Lambda)의 세계로 떠나볼 거예요.
 * 람다를 이해하려면, 먼저 '함수형 인터페이스'라는 개념을 알아야 합니다.
 *
 * [함수형 인터페이스란?]
 * - 아주 간단해요. "추상 메서드가 딱 하나만 있는 인터페이스"를 말합니다.
 * - 람다 표현식은 이름이 없는 '익명 함수'와 같아요. 그래서 이 함수가 어떤 모양(파라미터는 몇 개고, 반환 타입은 무엇인지)을 가져야 하는지 알려줄 '틀'이 필요합니다.
 * - 그 '틀'의 역할을 하는 것이 바로 이 함수형 인터페이스입니다.
 *
 * 아래 MyPrinter 인터페이스는 print라는 추상 메서드를 딱 하나만 가지고 있죠?
 * 그래서 함수형 인터페이스의 자격이 충분합니다.
 */

// @FunctionalInterface 어노테이션을 붙여주면,
// 컴파일러가 "이 인터페이스가 정말로 추상 메서드를 하나만 가지고 있는지" 검사해줍니다.
// 만약 개발자가 실수로 메서드를 추가하거나 없애면 에러를 발생시켜주는 고마운 안전장치예요.
@FunctionalInterface
public interface MyPrinter {

    // 이 인터페이스의 유일한 추상 메서드입니다.
    // "문자열(String) 하나를 받아서(파라미터), 아무것도 반환하지 않는(void) 기능을 수행해야 한다"는 규칙을 정의합니다.
    // 앞으로 우리가 만들 람다식은 바로 이 규칙을 따라야 합니다.
    void print(String message);

    // void sayHello(); // 만약 이렇게 두 번째 추상 메서드를 추가하면, @FunctionalInterface 어노테이션에서 바로 에러가 발생합니다.
}
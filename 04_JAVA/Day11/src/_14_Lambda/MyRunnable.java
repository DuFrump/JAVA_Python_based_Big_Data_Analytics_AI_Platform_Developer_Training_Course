package _14_Lambda;

/**
 * Java 선생님:
 * 이 인터페이스는 "아무것도 받지 않고(파라미터 없음), 아무것도 반환하지 않는(void)"
 * 가장 단순한 형태의 동작을 위한 '틀'입니다.
 *
 * "그냥 이 코드 블록을 실행해줘!" 라고 요청하는 모든 기능이 이 형태로 표현될 수 있습니다.
 * 예를 들어, "Hello World 출력하기", "파일 저장하기", "알림 보내기" 등이 있죠.
 *
 * Java의 스레드를 만들 때 사용하는 `Runnable` 인터페이스가 이와 완전히 동일한 구조를 가지고 있습니다.
 * 그래서 람다식이 등장한 이후, 스레드를 생성하는 코드가 매우 간결해졌답니다.
 *
 * 또한, "아무것도 받지 않고, 어떤 값을 반환하는" 형태는 `Supplier<T>` 라고 부릅니다.
 * (예: () -> "Hello")
 * "어떤 값을 받아서, 아무것도 반환하지 않는" 형태는 `Consumer<T>` 라고 부릅니다.
 * (예: s -> System.out.println(s))
 */
@FunctionalInterface
public interface MyRunnable {
    void run();
}
/**
 * 세 번째 시간은 퀴즈를 풀어보는 시간이에요!
 * 앞에서 배운 배열과 for문을 활용해서 실생활 문제를 해결해 볼 거예요.
 *
 * [퀴즈 내용]
 * 신발 가게에 250mm부터 295mm까지, 5mm 단위로 신발 사이즈가 준비되어 있어요.
 * 이 사이즈 목록을 배열을 사용해서 만들고, 예쁘게 출력하는 프로그램을 만들어 봅시다.
 *
 * 이런 문제를 보면 "아, 이건 배열을 쓰면 딱이겠다!" 라는 생각이 들면
 * 두프룸프님은 이미 프로그래머처럼 생각하고 있는 거랍니다! 멋져요!
 */
public class _03_Quiz {
    public static void main(String[] args) {

        // [문제 해결 과정]

        // 1. 먼저, 신발 사이즈를 담을 배열을 만들어야 해요.
        // 몇 칸짜리 배열이 필요할까요? 함께 세어볼까요?
        // 250, 255, 260, 265, 270, 275, 280, 285, 290, 295 -> 총 10개네요!
        // 그래서 10칸짜리 정수(int) 배열 'size'를 만듭니다.
        int[] size = new int[10];

        // 2. 이제 for문을 사용해서 10개의 빈 칸에 사이즈를 채워 넣을 거예요.
        // i가 0부터 9까지 변하는 동안, 일정한 규칙을 찾아 값을 넣어주면 됩니다.
        for (int i = 0; i < size.length; i++) { // size.length는 10이므로, i는 0부터 9까지 변해요.
            // 규칙을 찾아봅시다!
            // i = 0 일 때 -> 250 + (5 * 0) = 250
            // i = 1 일 때 -> 250 + (5 * 1) = 255
            // i = 2 일 때 -> 250 + (5 * 2) = 260
            // ...
            // i = 9 일 때 -> 250 + (5 * 9) = 295
            // 이렇게 시작값(250)에 (증가값(5) * i)를 더해주는 규칙을 찾았네요!
            size[i] = 250 + (5 * i);
        }

        // 3. 자, 이제 배열에 모든 사이즈가 잘 들어갔는지 확인해 볼 시간이에요.
        // for문을 다시 한번 사용해서 배열의 모든 요소를 하나씩 출력해 봅시다.
        System.out.println("--- 신발 사이즈 목록 ---");
        for (int i = 0; i < size.length; i++) {
            // size[i]에 저장된 사이즈 값을 가져와서 예쁜 문장과 함께 출력해요.
            System.out.println("사이즈 " + size[i] + " (재고 있음)");
        }

        /*
        [선생님 TIP]
        이렇게 배열과 반복문을 함께 사용하면, 수십, 수백 개의 데이터도
        아주 적은 양의 코드로 손쉽게 다룰 수 있게 된답니다.
        프로그래밍의 가장 강력한 무기 중 하나라고 할 수 있죠!
        */
    }
}
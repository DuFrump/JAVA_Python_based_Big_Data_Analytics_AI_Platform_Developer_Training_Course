// 배열을 사용하여 신발 사이즈 목록을 생성하고 출력하는 퀴즈입니다.

public class _03_Quiz {
    public static void main(String[] args) {

        // [문제] 신발 가게에 250mm부터 295mm까지 5mm 단위로 신발 사이즈가 있습니다.
        // 이 사이즈들을 배열에 저장하고 출력하세요.

        // 1. 신발 사이즈를 저장할 배열 선언 및 생성
        // 250, 255, ..., 295 (총 10개 사이즈)
        // (295 - 250) / 5 + 1 = 45 / 5 + 1 = 9 + 1 = 10
        int[] size = new int[10];

        // 2. 반복문을 사용하여 배열에 신발 사이즈 값 할당
        for (int i = 0; i < 10; i++) {
            size[i] = 250 + (5 * i); // 250부터 시작하여 5씩 증가하는 값을 할당
        }

        // 3. 반복문을 사용하여 배열에 저장된 신발 사이즈 출력
        System.out.println("--- 신발 사이즈 목록 ---");
        for (int i = 0; i < 10; i++) {
            System.out.println("사이즈 " + size[i] + " (재고 있음)");
        }

        /*
        // 예상 출력 결과:
        // 사이즈 250 (재고 있음)
        // 사이즈 255 (재고 있음)
        // 사이즈 260 (재고 있음)
        // 사이즈 265 (재고 있음)
        // 사이즈 270 (재고 있음)
        // 사이즈 275 (재고 있음)
        // 사이즈 280 (재고 있음)
        // 사이즈 285 (재고 있음)
        // 사이즈 290 (재고 있음)
        // 사이즈 295 (재고 있음)
        */
    }
}

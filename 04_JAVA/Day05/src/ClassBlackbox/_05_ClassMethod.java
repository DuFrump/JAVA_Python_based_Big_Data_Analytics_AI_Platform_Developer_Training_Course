package ClassBlackbox;

/**
 * 두프룸프님, 이번에는 '클래스 메소드(Class Method)'에 대해 배워볼게요.
 * 이전에 배운 '클래스 변수'와 짝을 이루는 개념이라고 생각하면 쉬워요.
 *
 * 클래스 메소드는 변수 앞에 `static`을 붙이는 것처럼, 메소드 앞에 `static`을 붙여서 만들어요.
 * 가장 큰 특징은, 객체(제품)를 만들지 않고도 `클래스이름.메소드이름()` 형태로 바로 호출해서 사용할 수 있다는 점이에요.
 *
 * 왜냐하면 클래스 메소드는 특정 객체의 데이터(인스턴스 변수)를 필요로 하지 않는, 클래스 자체의 공통 기능이기 때문입니다.
 * 예를 들어 "이 블랙박스 제품의 고객센터 전화번호가 뭐예요?" 같은 질문은, 특정 제품(까망이, 하양이)에 상관없이 모두 똑같은 답변을 주겠죠?
 * 바로 이런 기능들을 클래스 메소드로 만든답니다.
 */
public class _05_ClassMethod {
    public static void main(String[] args) {

        // [1] 클래스 메소드의 올바른 호출 방법
        // 아직 BlackBox 객체(b1, b2 등)를 하나도 만들지 않은 상태입니다.
        // 하지만 callServiceCentre() 메소드는 static(클래스 메소드)이기 때문에,
        // BlackBox 클래스 이름을 통해 바로 호출할 수 있습니다.
        System.out.println("--- 객체 생성 전 ---");
        BlackBox.callServiceCentre();

        // [2] 객체를 통한 호출도 가능은 하지만...?
        // 객체를 먼저 생성합니다.
        BlackBox b1 = new BlackBox();
        b1.modelName = "까망이";

        // 객체(b1)를 통해서도 클래스 메소드를 호출할 수는 있습니다.
        // 하지만 이클립스 같은 개발 도구에서 "이 static 메소드는 클래스 이름으로 접근해야 해!" 라고 노란 줄 경고를 보여줄 거예요.
        // 이 메소드는 b1이라는 특정 객체의 기능이 아니라, BlackBox 클래스 전체의 공통 기능이라는 것을 명확하게 하기 위함이죠.
        System.out.println("\n--- 객체 생성 후 ---");
        b1.callServiceCentre(); // 가능은 하지만 권장하지 않는 방법!

        /*
        [선생님 TIP - 아주 중요!]
        static 메소드 안에서는 인스턴스 변수(modelName, price 등)를 사용할 수 없어요!
        왜냐하면 static 메소드는 객체가 만들어지기 전에도 호출될 수 있는데,
        인스턴스 변수는 객체가 만들어져야만 존재하는 값이기 때문이죠.
        "아직 태어나지도 않은 b1 객체의 모델명이 뭐니?" 라고 묻는 것과 같은 이치랍니다.

        그래서 static 메소드 안에서는 static 변수만 사용할 수 있다는 점, 꼭 기억해 주세요!
        */
    }
}
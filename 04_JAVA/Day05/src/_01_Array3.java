/**
 * 안녕하세요, 두프룸프님! Java 선생님이에요.
 * 첫 번째 예제는 char 타입의 배열을 다뤄보는 시간입니다.
 *
 * 우리가 일상에서 'A', 'B', 'C' 같은 문자를 사용하듯이, 컴퓨터도 문자를 다룰 수 있어요.
 * 이 예제에서는 여러 문자가 섞여있는 배열에서 우리가 원하는 알파벳만 쏙쏙 골라내서
 * 의미있는 하나의 단어를 만들어 볼 거예요.
 *
 * 컴퓨터가 문자를 어떻게 숫자로 기억하는지(아스키 코드/유니코드)를 활용하면
 * 이런 재미있는 일도 할 수 있답니다. 함께 코드를 살펴볼까요?
 */
public class _01_Array3 {
    public static void main(String[] args) {

        // '1', 'L', 'O', '2', 'V', '3', 'E' 라는 문자 카드를 순서대로 가지고 있다고 상상해 보세요.
        // 이 카드들을 char 타입의 배열 'cards'에 담아두었습니다.
        char[] cards = {'1', 'L', 'O', '2', 'V', '3', 'E'};

        // 이제 이 카드들에서 알파벳만 골라내서 새로운 단어를 만들 거예요.
        // 완성된 단어를 저장하기 위해 비어있는 문자열 변수 'myWord'를 준비합니다.
        String myWord = "";

        // for문을 사용해서 'cards' 배열에 있는 카드를 처음부터 끝까지 하나씩 살펴볼 거예요.
        // i는 0부터 시작해서 배열의 길이(cards.length)보다 작을 때까지 1씩 증가합니다.
        for(int i = 0; i < cards.length; i++) {

            // 현재 확인하고 있는 카드(cards[i])를 컴퓨터가 이해하는 숫자로 잠시 바꿔서 'word'라는 정수 변수에 저장해요.
            // 예를 들어 'L'은 숫자 76, '1'은 숫자 49로 변환됩니다. (아스키 코드)
            int word = cards[i];

            // 이제 이 숫자가 알파벳에 해당하는 숫자인지 확인해 볼 시간이에요.
            // 대문자 A~Z는 숫자 65~90, 소문자 a~z는 97~122에 해당한답니다.
            // if 조건문은 "만약 'word'가 65 이상 90 이하 이거나, 또는 97 이상 122 이하 라면" 이라는 뜻이에요.
            if((word >= 65 && word <= 90) || (word >= 97 && word <= 122)) {
                // 와! 알파벳 카드를 찾았네요!
                // 그럼 이 숫자(word)를 다시 우리 눈에 보이는 문자(char)로 바꿔서 'myWord' 문자열의 뒤에 착! 붙여줍니다.
                // myWord = myWord + (char)word; 와 같은 의미입니다.
                myWord += (char)word;
            }
        }

        // 모든 카드를 확인하고 알파벳만 모았더니 어떤 단어가 만들어졌을까요?
        // 최종적으로 완성된 단어를 출력해 봅시다.
        System.out.println("여러분 " + myWord + " 합니다."); // 아마 "여러분 LOVE 합니다." 라고 출력될 거예요!

    }
}
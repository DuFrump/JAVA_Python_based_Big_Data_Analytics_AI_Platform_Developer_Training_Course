/**
 * 두프룸프님, 이번에는 프로그래밍의 중요한 개념 중 하나인 '정렬(Sort)'을 배워볼게요.
 * 그중에서도 가장 직관적이고 이해하기 쉬운 '버블 정렬(Bubble Sort)' 알고리즘을 살펴볼 거예요.
 *
 * 버블 정렬은 마치 물속의 공기방울이 위로 올라오는 것처럼,
 * 배열에 있는 숫자들을 비교해서 가장 큰 숫자를 맨 뒤로, 두 번째 큰 숫자를 그 앞으로,
 * 차곡차곡 순서대로 정렬하는 방법이랍니다.
 *
 * for문이 두 번 중첩되어 사용되는데, 왜 그런지, 그리고 두 숫자의 자리를 어떻게 바꾸는지(swap)
 * 집중해서 코드를 따라와 보세요!
 */
public class _04_Bubble {
    public static void main(String[] args) {

        // 정렬하고 싶은 숫자들을 담은 배열이에요. 순서가 뒤죽박죽이죠?
        int[] arr = {1, 6, 3, 7, 5, 9};
        int temp; // 두 숫자의 자리를 바꿀 때, 잠시 값을 저장해 둘 임시저장소(temporary) 변수예요.

        System.out.println("--- 버블 정렬 시작 ---");
        System.out.print("정렬 전 배열: ");
        printArray(arr); // 아래에 만든 printArray 메소드를 호출해서 현재 배열 상태를 출력해요.

        // 버블 정렬의 핵심 로직이 바로 여기, 중첩 for문에 있습니다.
        // 바깥쪽 for문 (i): 전체 정렬 과정을 몇 번 반복할지 결정해요. (배열 길이 - 1)번 만큼 돌아요.
        // 한 번 돌 때마다 가장 큰 숫자가 제자리를 찾아가기 때문에, 정렬할 범위가 하나씩 줄어들어요.
        for (int i = 0; i < arr.length - 1; i++) {

            // 안쪽 for문 (j): 실제로 이웃한 두 숫자를 비교하고 자리를 바꾸는 역할을 해요.
            // arr.length - 1 - i : 이 부분이 중요해요! 이미 정렬이 끝난 뒷부분은 비교할 필요가 없으니,
            // 비교 범위를 하나씩 줄여나가서 불필요한 작업을 막아준답니다.
            for (int j = 0; j < arr.length - 1 - i; j++) {

                // 만약 왼쪽 숫자(arr[j])가 오른쪽 숫자(arr[j+1])보다 크다면?
                // (오름차순 정렬이므로 작은 수가 왼쪽에 와야겠죠?)
                if(arr[j] > arr[j+1]) {
                    // 자리를 바꿔주자! (Swap)
                    // 1. temp라는 빈 컵에 왼쪽 컵(arr[j])의 내용물을 잠시 담아둡니다.
                    temp = arr[j];
                    // 2. 이제 비어있는 왼쪽 컵에 오른쪽 컵(arr[j+1])의 내용물을 붓습니다.
                    arr[j] = arr[j+1];
                    // 3. temp에 보관해뒀던 원래 왼쪽 컵의 내용물을 오른쪽 컵에 붓습니다.
                    arr[j+1] = temp;
                    // 이렇게 3단계를 거쳐야 두 변수의 값이 완벽하게 교환됩니다!
                }
            }
            // 안쪽 for문이 한 바퀴 다 돌면, 가장 큰 숫자가 맨 뒤로 이동했을 거예요.
            // 중간 과정을 한번 출력해 봅시다.
            System.out.print((i + 1) + "회차 정렬 후: ");
            printArray(arr);
        }

        System.out.println("\n--- 정렬 끝 ---");
        System.out.print("정렬 후 배열: ");
        printArray(arr); // 모든 정렬이 끝난 후의 최종 결과를 출력해요.
    }

    // [선생님 TIP] 이렇게 반복적으로 사용되는 코드는 별도의 메소드로 만들어두면 아주 편리해요.
    // 이 메소드는 정수 배열(int[] arr)을 받아서 그 안의 모든 숫자를 출력하는 역할을 합니다.
    public static void printArray(int[] arr) {
        // 향상된 for문(Enhanced for loop)을 사용했어요. 배열의 모든 요소를 처음부터 끝까지 순서대로 배치할 때 아주 간편해요.
        for (int num : arr) { // "arr 배열에 있는 모든 숫자(num)에 대하여 반복하라"는 의미입니다.
            System.out.print(num + " ");
        }
        System.out.println(); // 출력이 끝나면 줄바꿈!
    }
}

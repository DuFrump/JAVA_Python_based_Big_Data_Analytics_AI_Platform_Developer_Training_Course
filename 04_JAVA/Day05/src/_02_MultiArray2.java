/**
 * 두 번째 예제에 오신 것을 환영해요, 두프룸프님!
 * 이번에는 2차원 배열에 대해 배워볼 시간입니다.
 *
 * 1차원 배열이 기차처럼 한 줄로 쭉 늘어선 형태였다면,
 * 2차원 배열은 영화관 좌석이나 아파트처럼 행(row)과 열(column)이 있는 구조를 만들 때 사용해요.
 * 데이터를 좀 더 입체적으로 관리할 수 있게 되는 거죠.
 *
 * 이번 예제에서는 행과 열의 개수가 규칙적인 '정방형 배열'과
 * 행마다 열의 개수가 제각각인 '가변 배열(Jagged Array)'을 만드는 방법을 모두 살펴볼 거예요.
 * 코드를 보면서 2차원 배열과 친해져 봅시다!
 */
public class _02_MultiArray2 {
    public static void main(String[] args) {
        // [1] 정방형 2차원 배열: 모든 행의 열 개수가 똑같은 배열
        // 마치 잘 계획된 영화관의 좌석 배치도 같아요. 3줄(행), 각 줄마다 5칸(열)의 좌석이 있는 거죠.
        String[][] seats = new String[][] {
                {"A1", "A2", "A3", "A4", "A5"}, // 0번 행
                {"B1", "B2", "B3", "B4", "B5"}, // 1번 행
                {"C1", "C2", "C3", "C4", "C5"}  // 2번 행
        };

        System.out.println("--- 정방형 2차원 배열 출력 ---");
        // 2차원 배열의 모든 좌석을 출력하려면 for문이 두 번 필요해요. (중첩 for문)
        // 바깥 for문은 행(세로줄)을 담당합니다. i는 0, 1, 2 순서로 돌아요.
        for (int i = 0; i < 3; i++) {
            // 안쪽 for문은 열(가로칸)을 담당합니다. j는 0, 1, 2, 3, 4 순서로 돌아요.
            for (int j = 0; j < 5; j++) {
                // seats[i][j]는 "i번째 줄의 j번째 칸 좌석"을 의미해요. 예: seats[0][0] -> "A1"
                System.out.print(seats[i][j] + " ");
            }
            // 한 줄(행)의 출력이 모두 끝나면 다음 줄로 넘어가기 위해 줄바꿈을 해줍니다.
            System.out.println();
        }

        System.out.println("\n----------------------------------------\n");

        // [2] 가변 배열(Jagged Array): 행마다 열의 개수가 다른 배열
        // 어떤 줄은 좌석이 3개, 어떤 줄은 6개처럼 들쭉날쭉한 구조를 만들 때 유용해요.
        String[][] seats2 = {
                {"A1", "A2", "A3"},             // 0번 행: 좌석 3개
                {"B1", "B2", "B3", "B4"},         // 1번 행: 좌석 4개
                {"C1", "C2", "C3", "C4", "C5", "C6"}, // 2번 행: 좌석 6개
                {"D1", "D2"}                    // 3번 행: 좌석 2개
        };

        System.out.println("--- 가변 2차원 배열 출력 ---");
        // 가변 배열을 출력할 때는 고정된 숫자를 쓰는 대신, 배열의 길이를 직접 물어보는 게 안전해요.
        // 바깥 for문: seats2.length는 전체 행의 수(4)를 알려줍니다.
        for (int i = 0; i < seats2.length; i++) {
            // 안쪽 for문: seats2[i].length는 "i번째 행의 열 개수"를 알려줘요.
            // 예를 들어 i가 0일 때는 3, i가 2일 때는 6이 되겠죠?
            for (int j = 0; j < seats2[i].length; j++) {
                System.out.print(seats2[i][j] + " ");
            }
            System.out.println(); // 한 행 출력이 끝나면 줄바꿈!
        }

        System.out.println("\n----------------------------------------\n");

        // [3] 2차원 배열 응용: 좌석 배치도 자동으로 만들기
        // 10행 15열의 큰 영화관 좌석을 코드로 직접 만들어 볼게요.
        int[][] seats3 = new int[10][15]; // 10x15 크기의 정수형 2차원 배열 공간만 우선 만들어요.
        String[] eng = {"A", "B", "C", "D", "E", "F", "G", "H", "I", "J"}; // 행 이름으로 쓸 알파벳 배열

        // 중첩 for문으로 각 좌석에 1부터 15까지의 번호를 매겨줍니다.
        for (int i = 0; i < 10; i++) { // 10개의 행을 순서대로 돌면서
            int count = 1; // 각 행이 시작될 때마다 좌석 번호를 1로 리셋!
            for (int j = 0; j < 15; j++) { // 15개의 열을 순서대로 돌면서
                seats3[i][j] = count++; // 현재 좌석에 count 값을 넣고, count를 1 증가시켜 다음 좌석을 준비해요.
            }
        }

        System.out.println("--- 좌석 배치도 생성 및 출력 ---");
        // 이제 멋지게 만들어진 좌석 배치도를 출력해 봅시다.
        for (int i = 0; i < 10; i++) { // 행 순회
            for (int j = 0; j < 15; j++) { // 열 순회
                // printf를 사용하면 형식을 지정해서 출력할 수 있어요.
                // %s는 문자열(String), %d는 정수(decimal)를 의미해요.
                // eng[i]에서 알파벳을, seats3[i][j]에서 좌석 번호를 가져와 조합합니다. (예: A1, A2 ...)
                System.out.printf("%s%d ", eng[i], seats3[i][j]);
            }
            System.out.println(); // 한 행 출력이 끝나면 줄바꿈!
        }
    }
}
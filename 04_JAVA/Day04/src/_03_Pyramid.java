/**
 * 두프룸프님, 이번 예제는 정말 재미있을 거예요! 바로 '별 찍기'입니다.
 * 중첩 for문을 응용해서 콘솔 화면에 다양한 모양의 피라미드와 도형을 그려볼 거예요.
 * 단순한 반복을 넘어, 반복문의 변수(i, j)를 어떻게 조작하느냐에 따라
 * 이렇게 예쁜 그림을 그릴 수 있다는 점이 프로그래밍의 큰 매력 중 하나랍니다.
 *
 * 이 예제를 통해 우리는...
 * 1. 바깥쪽 for문이 '줄(행)'을 제어하고, 안쪽 for문이 '칸(열)'을 제어하는 원리를 시각적으로 이해하게 됩니다.
 * 2. 공백과 별을 조합하여 원하는 모양을 만드는 논리적인 사고력을 기를 수 있습니다.
 * 3. 변수의 변화에 따른 출력 결과의 패턴을 파악하는 능력을 키울 수 있습니다.
 *
 * 자, 이제부터 우리만의 작은 예술 작품을 만들어 볼까요?
 */
public class _03_Pyramid {
    public static void main(String[] args) {
        // [1] 왼쪽 정렬된 직각 삼각형 (별이 점점 늘어나는 모양)
        // 1층엔 1개, 2층엔 2개, ... 10층엔 10개의 별을 찍어볼게요.
        System.out.println("--- 왼쪽 정렬 직각 삼각형 (증가) ---");
        for (int i = 0; i < 10; i++) { // 바깥 for문: 0층부터 9층까지, 총 10개의 층(줄)을 만들어요.
            // 안쪽 for문: 현재 층(i)의 수만큼 별을 찍어요. i가 0일땐 1번, 1일땐 2번... 실행되도록 j <= i 조건을 사용해요.
            for (int j = 0; j <= i; j++) {
                System.out.print("*"); // print()는 줄바꿈 없이 옆으로 계속 출력해요.
            }
            System.out.println(); // 한 층의 별을 다 찍었으면, 다음 층으로 넘어가기 위해 줄바꿈(엔터)을 해줍니다.
        }

        System.out.println("----------------------------------------");

        // [2] 정중앙에 놓인 피라미드 (정삼각형)
        // 이건 조금 더 생각해야 해요! 별을 찍기 전에, 왼쪽에 '공백'을 먼저 찍어서 별을 오른쪽으로 밀어줘야 하거든요.
        System.out.println("--- 정삼각형 (피라미드) ---");
        for (int i = 1; i <= 10; i++) { // 1층부터 10층까지 만들어 볼게요.
            // 첫 번째 안쪽 for문: '공백'을 찍는 역할. 꼭대기 층은 공백이 많고, 아래로 갈수록 공백이 줄어들어야겠죠?
            // 그래서 (전체 층수 - 현재 층수) 만큼 공백을 찍습니다.
            for (int k = 0; k < 10 - i; k++) {
                System.out.print(" ");
            }

            // 두 번째 안쪽 for문: '별'을 찍는 역할. 별은 1, 3, 5, 7... 홀수 개수로 늘어나요.
            // (현재 층수 * 2 - 1) 이라는 규칙을 발견할 수 있어요!
            for (int j = 0; j < (i * 2) - 1; j++) {
                System.out.print("*");
            }
            System.out.println(); // 한 층의 공백과 별을 모두 찍었으면 줄바꿈!
        }

        System.out.println("----------------------------------------");

        // [3] 왼쪽 정렬된 역직각 삼각형 (별이 점점 줄어드는 모양)
        // [1]번 삼각형을 거꾸로 뒤집은 모양이에요.
        System.out.println("--- 왼쪽 정렬 역직각 삼각형 (감소) ---");
        for (int i = 0; i < 10; i++) { // 층(줄)을 만드는 바깥 for문은 동일해요.
            // 안쪽 for문: 이번엔 별의 개수가 10개, 9개, 8개... 순으로 줄어들어야 해요.
            // (전체 층수 - 현재 층수) 만큼 별을 찍으면 자연스럽게 줄어드는 모양이 된답니다.
            for (int j = 0; j < 10 - i; j++) {
                System.out.print("*");
            }
            System.out.println();
        }

        System.out.println("----------------------------------------");

        // [4] 오른쪽 정렬된 직각 삼각형
        // [2]번 피라미드와 비슷해요. 공백으로 밀어주고, 별을 찍으면 됩니다.
        System.out.println("--- 오른쪽 정렬 직각 삼각형 (증가) ---");
        for (int i = 0; i <= 10; i++) { // 0층부터 10층까지
            // 공백 찍기: 10, 9, 8... 순으로 줄어들어야 하니 (10 - i) 만큼 찍어요.
            for (int j = 0; j < 10 - i; j++) {
                System.out.print(" ");
            }
            // 별 찍기: 0, 1, 2... 순으로 늘어나야 하니 i 만큼 찍어요.
            for (int k = 0; k < i; k++) {
                System.out.print("*");
            }
            System.out.println();
        }

        System.out.println("----------------------------------------");

        // [5] 다이아몬드 (마름모) 모양
        // 이건 위에서 만든 [2]번 정삼각형과, 그걸 뒤집은 역정삼각형을 합친 모양이에요.
        // 조금 더 스마트한 방법으로 만들어 볼까요?
        System.out.println("--- 다이아몬드 (마름모) ---");
        int n = 5; // 다이아몬드 크기 (중심으로부터의 최대 반경)

        // 위쪽 삼각형 부분 (중심 포함)
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= n - i; j++) { // 공백
                System.out.print(" ");
            }
            for (int j = 1; j <= 2 * i - 1; j++) { // 별
                System.out.print("*");
            }
            System.out.println();
        }

        // 아래쪽 삼각형 부분
        for (int i = n - 1; i >= 1; i--) {
            for (int j = 1; j <= n - i; j++) { // 공백
                System.out.print(" ");
            }
            for (int j = 1; j <= 2 * i - 1; j++) { // 별
                System.out.print("*");
            }
            System.out.println();
        }
    }
}
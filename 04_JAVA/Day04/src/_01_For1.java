/**
 * 안녕하세요, 두프룸프님! Java의 세계에 오신 것을 환영합니다.
 * 오늘은 프로그래밍의 핵심 중 하나인 'for 반복문'에 대해 배워볼 거예요.
 * for문은 마치 우리가 운동장을 정해진 바퀴 수만큼 돌거나, 책을 특정 페이지까지 읽는 것처럼
 * 컴퓨터에게 정해진 횟수만큼 특정 작업을 반복하도록 시킬 때 사용하는 아주 유용한 도구랍니다.
 *
 * 이 예제에서는 for문의 기본적인 구조부터 시작해서,
 * 숫자의 합계를 구하거나, 역순으로 숫자를 출력하고, 특정 조건에 맞는 숫자만 골라내는 등
 * 다양한 활용법을 함께 살펴볼 거예요.
 * 하나씩 따라 하다 보면 어느새 for문과 절친이 되어 있을 거예요! 자, 시작해볼까요?
 */
public class _01_For1 {
    public static void main(String[] args) {
        // [1] for문의 가장 기본적인 형태입니다. "안녕하세요"를 10번 출력해 볼게요.
        // for (초기화식; 조건식; 증감식) { ... }
        // 1. 초기화식 (int i = 0;): for문이 시작될 때 딱 한 번만 실행돼요. 반복 횟수를 세는 기준 변수 i를 0으로 만듭니다.
        // 2. 조건식 (i < 10;): 코드를 실행하기 전에 매번 i가 10보다 작은지 검사해요. 맞으면(true) { } 안의 코드를 실행하고, 틀리면(false) for문을 끝냅니다.
        // 3. 증감식 (i++): { } 안의 코드를 한 번 실행한 후에 i 값을 1 증가시킵니다. i는 0, 1, 2, ... , 9 까지 변하면서 총 10번 반복하게 되죠.
        System.out.println("--- 10번 반복 출력 ---");
        for(int i = 0; i < 10; i++) { // i가 0부터 9까지 변하므로 총 10번 반복해요.
            System.out.println("안녕하세요. " + (i + 1) + "번째 인사입니다!");
        }

        System.out.println("\n----------------------------------------\n");

        // [2] for문을 이용해서 0부터 9까지의 숫자를 모두 더해볼까요?
        int sum = 0; // 합계를 저장할 변수를 만들고, 처음에는 아무것도 더하지 않았으니 0으로 초기화해요.
        System.out.println("--- 0부터 9까지의 합계 ---");
        for (int i = 0; i < 10; i++) {
            // sum = sum + i; 와 같은 뜻이에요. 기존 sum에 i값을 계속 더해나가는 거죠.
            // i=0일 때: sum = 0 + 0 = 0
            // i=1일 때: sum = 0 + 1 = 1
            // i=2일 때: sum = 1 + 2 = 3
            // ... 이렇게 i가 9가 될 때까지 반복해요.
            sum += i;
        }
        System.out.println("0부터 9까지의 합계: " + sum); // 최종 결과인 45가 출력됩니다.

        System.out.println("\n----------------------------------------\n");

        // [3] 이번엔 숫자를 거꾸로 세어볼까요? 5부터 1까지 출력해 봅시다.
        System.out.println("--- 5부터 1까지 역순 출력 ---");
        // 1. 초기화식 (int i = 5;): i를 5에서부터 시작해요.
        // 2. 조건식 (i > 0;): i가 0보다 클 때까지 반복해요.
        // 3. 증감식 (i--): i를 1씩 감소시킵니다. i는 5, 4, 3, 2, 1 순서로 변하겠죠?
        for (int i = 5; i > 0; i--) {
            System.out.println(i);
        }

        System.out.println("\n----------------------------------------\n");

        // [4] 꼭 1씩 변하란 법은 없어요. 2씩 점프하면서 1부터 10까지의 홀수만 출력해 볼까요?
        System.out.println("--- 1부터 10까지 홀수만 출력 ---");
        // 증감식을 i += 2 로 설정하면 i가 1, 3, 5, 7, 9 로 2씩 증가하게 됩니다.
        for (int i = 1; i <= 10; i += 2) {
            System.out.println(i);
        }

        System.out.println("\n----------------------------------------\n");

        // [5] 응용 문제! 1부터 100까지의 합계를 구해봅시다.
        sum = 0; // 위에서 썼던 sum 변수를 다시 사용하기 전에 0으로 깨끗하게 만들어줘요.
        System.out.println("--- 1부터 100까지의 합계 ---");
        for (int i = 1; i <= 100; i++) { // i가 1부터 100까지 1씩 증가하며 반복해요.
            sum += i;
        }
        System.out.println("1부터 100까지의 합계: " + sum); // 5050이 나올 거예요!

        System.out.println("\n----------------------------------------\n");

        // [6] 조금 더 어려운 응용! 1부터 100까지의 숫자 중 '짝수'만 더해볼까요?
        sum = 0; // sum 변수를 다시 0으로 초기화!
        System.out.println("--- 1부터 100까지 짝수의 합계 ---");
        for (int i = 1; i <= 100; i++) {
            // if문을 사용해서 i가 짝수일 때만 더하도록 조건을 걸어주는 거예요.
            // i % 2 == 0 은 'i를 2로 나눈 나머지가 0과 같다면' 이라는 뜻으로, 짝수를 판별하는 공식이에요.
            if(i % 2 == 0) {
                sum += i; // 짝수일 때만 sum에 더합니다.
            }
        }
        System.out.println("1부터 100까지 짝수의 합계: " + sum); // 2550이 맞나요?
    }
}
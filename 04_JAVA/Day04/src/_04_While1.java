/**
 * 두프룸프님, 이번에는 for문의 단짝 친구, 'while 반복문'을 만나볼 시간입니다.
 * for문이 정해진 횟수(운동장 10바퀴)를 반복하는 데 강점이 있다면,
 * while문은 특정 조건이 만족되는 동안(배가 부를 때까지) 계속 반복하는 데 특화되어 있어요.
 * '~하는 동안은 계속해!' 라는 느낌이죠.
 *
 * 이 예제에서는 while문의 기본적인 사용법을 배우고,
 * for문으로 작성했던 코드를 while문으로 똑같이 구현해보면서 둘의 차이점과 공통점을 느껴볼 거예요.
 * while문을 사용할 때 가장 주의해야 할 점은 바로 '무한 루프'랍니다.
 * 반복을 멈추게 할 탈출 조건을 꼭 만들어줘야 한다는 점, 잊지 마세요!
 */
public class _04_While1 {
    public static void main(String[] args) {
        // [1] while문을 이용해서 1부터 10까지의 합계를 구해봅시다.
        int sum = 0; // 합계를 저장할 변수
        int i = 1;   // for문의 초기화식(int i=1)에 해당하는 부분을 while문에서는 미리 만들어줘야 해요.

        // while (조건식) { ... }
        // while문은 소괄호 안의 조건식이 참(true)인 동안에만 { } 안의 코드를 반복 실행해요.
        System.out.println("--- while문 시작! ---");
        while (i <= 10) { // "i가 10보다 작거나 같은 동안은 계속 반복할게!"
            System.out.println(i + "번째 반복 중... 현재 합계: " + sum);
            sum += i; // sum = sum + i;

            // ★★★★★ 가장 중요한 부분! ★★★★★
            // for문의 증감식(i++)에 해당하는 부분이에요. i값을 1씩 증가시켜서
            // 언젠가는 조건식(i <= 10)이 거짓(false)이 되도록 만들어야 해요.
            // 이 코드가 없으면 i는 영원히 1이고, while문은 절대 끝나지 않는 '무한 루프'에 빠집니다!
            i++;
        }
        System.out.println("--- while문 종료! ---");
        System.out.println("1부터 10까지의 최종 합계: " + sum);

        System.out.println("\n----------------------------------------\n");

        // [2] for문과 while문 비교해보기
        // 똑같은 기능을 하는 코드도 for문으로 쓸 수 있고, while문으로도 쓸 수 있어요.
        // 보통은 for문처럼 반복 횟수가 명확하게 정해진 경우에는 for문을 쓰는게 코드가 더 깔끔하고,
        // while문은 반복 횟수보다는 특정 조건을 만족할 때까지 계속해야 할 때 더 유용하답니다.

        System.out.println("--- for문으로도 똑같이 계산해보기 ---");
        int sumFor = 0;
        // for문은 초기화, 조건식, 증감식이 한 줄에 모두 모여있어서 가독성이 좋죠?
        for (int j = 1; j <= 10; j++) {
            sumFor += j;
        }
        System.out.println("for 문으로 계산한 합계: " + sumFor);

        System.out.println("\n결론: for문과 while문은 서로 바꿀 수 있지만, 상황에 맞게 쓰는 센스를 기르는게 중요해요!");
    }
}
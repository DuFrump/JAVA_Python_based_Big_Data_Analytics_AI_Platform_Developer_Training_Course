/**
 * 두프룸프님, 이번에는 while문의 사촌 격인 'do-while 반복문'을 배워보겠습니다.
 * while문과 거의 똑같지만, 딱 한 가지 결정적인 차이가 있어요.
 * while문은 조건을 '먼저' 검사하고 실행 여부를 결정하지만 (선검사 후실행),
 * do-while문은 '일단 먼저 한 번 실행'하고 나서 조건을 검사한다는 점입니다 (선실행 후검사).
 *
 * 그래서 조건이 처음부터 거짓(false)이더라도, do-while문의 { } 안의 코드는
 * 최소 한 번은 반드시 실행되는 특징을 가지고 있습니다.
 * 마치 맛보기 코너에서 "일단 한 번 드셔보세요!" 하고 먼저 권하는 것과 같죠.
 *
 * 이 예제를 통해 do-while문의 동작 순서를 이해하고, 어떤 상황에서 유용하게 쓰일 수 있는지 알아볼게요.
 */
public class _05_DoWhile {
    public static void main(String[] args) {
        // [1] do-while문으로 1부터 10까지의 합계를 구해봅시다.
        int sum = 0;
        int i = 1;

        // do { ... } while(조건식);
        // while문과 달리 세미콜론(;)으로 끝나는 점도 주목해주세요!
        System.out.println("--- do-while문 시작! ---");
        do {
            // 1. 일단 do { } 블록 안으로 들어와서 코드를 실행합니다.
            System.out.println(i + "번째 반복! 일단 실행부터 합니다.");
            sum += i;
            i++;
        } while (i <= 10); // 2. 코드를 한 번 실행한 '이후'에 조건을 검사합니다. 참이면 다시 do블록으로 올라가요.

        System.out.println("--- do-while문 종료! ---");
        System.out.println("1부터 10까지의 합계: " + sum);

        System.out.println("\n----------------------------------------\n");

        // [2] do-while문의 '최소 1회 실행' 특징을 직접 확인해볼까요?
        int j = 100; // 변수 j의 시작값을 100으로 설정해볼게요.

        System.out.println("--- while문과 비교해보기 ---");
        // 일반 while문이었다면 어땠을까요?
        // 시작부터 조건(100 <= 10)이 거짓(false)이므로, 안의 코드는 단 한 번도 실행되지 않아요.
        while (j <= 10) {
            System.out.println("이 메시지는 일반 while문이었다면 절대 보이지 않았을 거예요.");
        }

        System.out.println("\n--- do-while 최소 1회 실행 예제 ---");
        j = 100; // j를 다시 100으로.
        do {
            // 하지만 do-while문은 조건을 나중에 검사하기 때문에, 일단 한 번은 실행됩니다!
            System.out.println("j가 100이라 조건이 명백히 거짓이지만, 이 메시지는 출력됩니다! 현재 j값: " + j);
            j++;
        } while (j <= 10); // 실행이 끝난 후, 여기서 (101 <= 10)을 검사하고 거짓이므로 반복을 종료합니다.

        System.out.println("\n반복이 끝난 후 j의 값은? " + j); // do-while문 안에서 j++가 한 번 실행되었기 때문에 101이 됩니다.
    }
}
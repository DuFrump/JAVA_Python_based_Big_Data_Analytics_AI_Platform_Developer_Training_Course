/**
 * 두프룸프님, 이번에는 한 단계 더 나아가 '중첩 for문'에 대해 배워볼 시간이에요.
 * for문 안에 또 다른 for문이 들어간 구조를 말하는데, 어렵게 생각할 필요 없어요.
 * 바깥 for문이 한 번 실행될 때마다, 안쪽 for문은 처음부터 끝까지 실행되는 모습을 상상해보세요.
 * 마치 아파트의 각 층(바깥 for문)마다 있는 호수(안쪽 for문)를 하나씩 방문하는 것과 같답니다.
 *
 * 이 예제에서는 중첩 for문을 이용해서 인사를 반복하고,
 * 우리에게 아주 익숙한 '구구단'을 세로와 가로, 두 가지 형태로 출력해 볼 거예요.
 * 중첩 for문의 동작 원리를 이해하면, 평면적인 반복을 넘어 입체적인 반복 작업을 처리할 수 있게 된답니다.
 * 준비됐나요? 신기한 중첩 for문의 세계로 떠나봅시다!
 */
public class _02_For2 {
    public static void main(String[] args) {

        // [1] 중첩 for문의 기본 원리 이해하기: 5개의 방에 있는 5명의 형님에게 인사하기!
        int count = 0; // 총 몇 번 인사했는지 횟수를 세기 위한 변수에요.

        // 바깥쪽 for문 (Outer loop): 1번 방부터 5번 방까지, 총 5개의 방을 차례로 방문해요.
        for (int i = 1; i <= 5; i++) {
            System.out.printf("\n === %d번 방에 들어왔습니다. === %n", i);

            // 안쪽 for문 (Inner loop): 현재 들어온 방에 있는 1번 형님부터 5번 형님까지 차례로 인사를 드려요.
            // 바깥쪽 for문의 i가 1일 때, j는 1~5까지 반복합니다.
            // 바깥쪽 for문의 i가 2일 때, j는 또 1~5까지 반복합니다.
            // ... 이렇게 i가 5일 때까지 반복되겠죠?
            for (int j = 1; j <= 5; j++) {
                System.out.printf("(%d번 방의 %d번 형님께) 안녕하세요!%n", i, j);
                count++; // 인사를 한 번 할 때마다 횟수를 1씩 증가시켜요.
            }
        }
        // 총 인사 횟수는? 바깥쪽 반복 횟수(5) * 안쪽 반복 횟수(5) = 25번이 됩니다.
        System.out.printf("\n총 인사 횟수: %d번 입니다!%n", count);


        // [2] 응용: 세로로 출력되는 구구단 만들기
        System.out.println("\n\n=========================> 세로 구구단 <=========================");

        // 구구단의 제목(타이틀) 부분을 먼저 출력해줘요. 보기 좋게 탭(\t)으로 간격을 맞춥니다.
        for (int title = 2; title < 10; title++) {
            System.out.print("<" + title + "단>\t\t");
        }
        System.out.println(); // 제목을 다 출력했으면 한 줄 내려줘야겠죠?

        // 바깥쪽 for문: 곱해지는 수 (1부터 9까지 변해요. 구구단의 세로줄을 담당)
        for (int i = 1; i < 10; i++) {
            // 안쪽 for문: 단수 (2단부터 9단까지 변해요. 구구단의 가로줄을 담당)
            for (int j = 2; j < 10; j++) {
                int result = j * i;
                // printf를 사용해서 "2x1=2" 와 같은 형태로, 간격을 맞춰 출력해요.
                System.out.printf("%dx%d=%-2d\t", j, i, result);
            }
            System.out.println(); // 2단부터 9단까지의 x1 계산이 모두 끝나면 한 줄 내려줍니다. 그리고 다시 i가 2가 되어 반복...
        }


        // [3] 응용: 가로로 출력되는 구구단 만들기
        System.out.printf("\n\n=================================> 가로 구구단 <=================================");

        // 바깥쪽 for문: 단수 (2단부터 9단까지, 구구단의 한 단 전체를 담당)
        for (int i = 2; i < 10; i++) {
            System.out.printf("\n<%d단>\t", i);

            // 안쪽 for문: 곱해지는 수 (1부터 9까지, 각 단의 내용을 담당)
            for (int j = 1; j < 10; j++) {
                int result = i * j;
                System.out.printf("%dx%d=%-2d\t", i, j, result);
            }
        }
        System.out.println();
    }
}
// 자바 프로그램의 가장 기본적인 구조를 보여주는 예제 코드입니다.

/**
 * 여러 줄 주석입니다.
 * 이 주석은 클래스나 메소드에 대한 상세한 설명을 작성할 때 주로 사용됩니다.
 *
 * [클래스(Class)]
 * 자바의 모든 코드는 클래스라는 단위 안에 작성되어야 합니다.
 * 클래스는 관련된 데이터(변수)와 기능(메소드)을 하나로 묶어놓은 설계도와 같습니다.
 * public: "이 클래스는 어디서든 접근 가능하다"는 의미의 접근 제어자입니다.
 * class: 클래스를 정의할 때 사용하는 키워드입니다.
 * _01_JavaStart: 클래스의 이름입니다. 일반적으로 소스 파일명과 동일하게 작성합니다.
 */
public class _01_JavaStart {

    /**
     * [메인 메소드(Main Method)]
     * main 메소드는 자바 프로그램이 실행될 때 가장 먼저 호출되는, 즉 프로그램의 시작점입니다.
     *
     * public: "이 메소드는 어디서든 접근 가능하다"는 의미입니다. main 메소드는 항상 public으로 선언해야 합니다.
     * static: "이 메소드는 객체를 생성하지 않고도 바로 실행할 수 있다"는 의미입니다.
     *         프로그램 시작 시점에 _01_JavaStart 클래스의 객체가 없으므로 static으로 선언해야 합니다.
     * void: "이 메소드는 실행 후 아무런 값도 반환하지 않는다"는 의미입니다.
     * main: 자바 가상 머신(JVM)이 프로그램을 시작하기 위해 찾는 메소드의 이름입니다.
     * (String[] args): 프로그램을 실행할 때 외부에서 전달하는 값(인자)을 받는 부분입니다.
     *                   예를 들어, `java _01_JavaStart hello world` 라고 실행하면
     *                   args 배열에는 "hello"와 "world"라는 문자열이 담기게 됩니다.
     */
    public static void main(String[] args) {
        // System.out.println("...");
        // System.out: 자바의 표준 출력 스트림(일반적으로 콘솔 화면)을 의미합니다.
        // println(): 괄호 안의 내용을 출력하고 줄을 바꾸는(print line) 역할을 합니다.
        // 문자열(String) 데이터를 출력할 때는 큰따옴표("")로 감싸줍니다.
        System.out.println("Hi, Java. Nice to meet you!");

        // println() 안에 아무 내용도 넣지 않으면, 아무것도 출력하지 않고 줄바꿈만 실행합니다.
        System.out.println();

        // 숫자 데이터도 출력할 수 있습니다. 숫자는 큰따옴표로 감싸지 않습니다.
        System.out.println(12345);

        // 간단한 연산의 결과도 바로 출력할 수 있습니다.
        System.out.println(10 + 5);
    }
}
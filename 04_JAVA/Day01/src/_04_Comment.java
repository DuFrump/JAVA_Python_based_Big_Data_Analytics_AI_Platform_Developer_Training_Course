// 주석(Comment)의 종류와 올바른 사용법을 배우는 예제입니다.

public class _04_Comment {

    /*
     * [주석(Comment)이란?]
     * - 코드에 대한 설명을 작성하는 부분으로, 프로그램의 실행에는 전혀 영향을 주지 않습니다.
     * - 컴파일러(번역기)가 주석 부분은 무시하고 코드를 번역합니다.
     *
     * [주석을 사용하는 이유]
     * 1. 코드 설명: 복잡한 로직이나 특정 코드의 의도를 설명하여 다른 개발자(또는 미래의 나)가 쉽게 이해할 수 있도록 돕습니다.
     * 2. 임시 비활성화: 코드의 특정 부분을 잠시 실행하지 않도록 만들고 싶을 때 사용합니다. (디버깅 시 유용)
     * 3. 정보 기록: 코드 작성자, 작성일, 수정 이력 등 메타 정보를 남길 수 있습니다.
     */

    public static void main(String[] args) {

        // --- 1. 한 줄 주석 (Single-line Comment) ---
        // `//` 기호가 나온 시점부터 그 줄의 끝까지를 주석으로 처리합니다.
        // 간단한 설명이나 코드 한 줄을 임시로 비활성화할 때 주로 사용합니다.

        System.out.println("(5분) 일찍 오기"); // 약속 시간보다 5분 일찍 오자는 다짐을 출력

        // 아래 두 줄은 주석 처리되어 실행되지 않습니다.
        // System.out.println("하지만 비가 와서 쉽지 않아요.");
        // System.out.println("그래도 일찍 와야겠죠?");


        // --- 2. 여러 줄 주석 (Multi-line Comment) ---
        // `/*` 와 `*/` 사이의 모든 내용을 주석으로 처리합니다.
        // 여러 줄에 걸친 긴 설명이나 여러 코드 라인을 한 번에 비활성화할 때 유용합니다.

        /*
        System.out.println("이 부분은");
        System.out.println("여러 줄 주석 처리되어");
        System.out.println("실행되지 않습니다.");
        */


        // --- 3. 문서 주석 (JavaDoc Comment) ---
        // `/**` 와 `*/` 사이의 내용으로, 클래스나 메소드에 대한 설명을 작성할 때 사용합니다.
        // 나중에 javadoc 이라는 도구를 사용하여 API 문서를 자동으로 생성할 수 있습니다.
        // (지금은 여러 줄 주석과 기능이 비슷하다고 생각해도 좋습니다.)

        // --- 주석 활용 예시: 코드 설명 ---
        int shoeSize = 260; // 신발 사이즈를 저장하는 변수

        // 사이즈를 10 늘리는 이유에 대한 설명 (예: 겨울용 두꺼운 양말을 신기 위해)
        shoeSize = shoeSize + 10;

        System.out.println("겨울용 신발 사이즈는 " + shoeSize + "mm 입니다.");


        // [좋은 주석 작성 Tip]
        // - "무엇(What)"을 하는 코드인지 보다는, "왜(Why)" 그렇게 작성했는지를 설명하는 것이 좋습니다.
        // - 코드를 그대로 설명하는 주석은 피하는 것이 좋습니다. (예: `int i = 10; // i에 10을 넣는다.` -> 불필요한 주석)
        // - 코드가 변경되면 주석도 반드시 함께 수정해야 합니다.


        // [IDE 주석 단축키]
        // 한 줄 주석 설정/해제: Ctrl + /
        // 여러 줄 주석 설정/해제: Ctrl + Shift + /
        // (사용하는 IDE나 운영체제에 따라 단축키는 다를 수 있습니다.)
    }
}
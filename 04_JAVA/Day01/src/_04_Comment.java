// 주석(Comment)의 사용법을 배우는 예제입니다.
// 주석은 코드에 대한 설명을 작성하는 부분으로, 프로그램 실행에는 영향을 주지 않습니다.

public class _04_Comment {
    public static void main(String[] args) {
        System.out.println("(5분) 일찍 오기 ");

        // 한 줄 주석: // 기호 뒤의 모든 내용은 주석으로 처리됩니다.
        // System.out.println("하지만 비가 와서 쉽지 않아요."); // 이 부분은 실행되지 않습니다.
        // System.out.println("그래도 일찍 와야겠죠?"); // 이 부분도 실행되지 않습니다.

        // 변수 선언 및 값 변경
        int size = 120;
        size = size + 10; // 기존 size 값(120)에 10을 더한 결과를 다시 size에 저장합니다. (size는 130이 됨)

        // 주석을 사용하여 코드의 특정 부분을 설명할 수 있습니다.
        // 아래 코드에서 (size - 10)은 120이 아니라 130 - 10 = 120이 됩니다.
        // 하지만 출력되는 문자열은 "사이즈는 120입니다."가 됩니다.
        // size 변수의 최종값은 130이지만, 출력문에서는 (size-10)으로 계산하여 120을 출력하고 있습니다.
        System.out.println("사이즈는 " + (size - 10) + "입니다."); // 출력 결과: 사이즈는 120입니다.

        // 여러 줄 주석: /* 와 */ 사이의 모든 내용은 주석으로 처리됩니다.
        /*
        int a = 10;
        int b = 20;
        System.out.println(a + b);
        */

        // 여러 변수를 선언하고 한 번에 계산하여 출력합니다.
        int a = 10;
        int b = 20;
        int c = 30;
        int d = 40;
        System.out.println(a + b + c + d); // 10 + 20 + 30 + 40 = 100

        // 주석 단축키 정보 (IDE마다 다를 수 있음)
        // 한 줄 주석 단축키 : Ctrl + /
        // 여러 줄 주석 단축키 : Ctrl + Shift + /
    }
}

// 다양한 종류의 데이터 타입을 출력하는 예제입니다.

public class _02_DataTypes {
    public static void main(String[] args) {
        // 문자열 (String): 큰따옴표("")로 묶인 텍스트 데이터입니다.
        System.out.println("When I was young, I used to listen a radio.");
        System.out.println("난 어릴 적에 라디오를 듣곤 했어.");

        // 숫자 (Number)
        // 정수 (Integer): 소수점이 없는 숫자입니다.
        System.out.println(12);
        System.out.println(-55);

        // 실수 (Floating-point): 소수점이 있는 숫자입니다.
        System.out.println(0.445);

        // 불리언 (Boolean): 참(true) 또는 거짓(false) 값을 나타냅니다.
        System.out.println(true);
        System.out.println(false);

        // 간단한 연산도 가능합니다.
        // 덧셈 연산의 결과를 출력합니다.
        System.out.println(5 + 6);
    }
}

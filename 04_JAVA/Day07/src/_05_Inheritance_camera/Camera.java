package _05_Inheritance_camera;

/**
 * 다섯 번째 예제에 오신 것을 환영합니다!
 * 이번에는 '카메라'를 예시로 상속의 다양한 활용법을 배워볼 거예요.
 * 특히, '생성자 오버로딩'과 'this()를 이용한 생성자 호출',
 * 그리고 'protected' 접근 제어자가 생성자에 사용될 때의 의미를 집중적으로 살펴볼 겁니다.
 *
 * 이 Camera 클래스는 모든 카메라가 공통적으로 가질 수 있는 '이름', '사진 촬영', '동영상 녹화' 등의
 * 기본적인 속성과 기능을 정의하는 '부모 클래스' 역할을 합니다.
 */
public class Camera {
    // === 필드 (Fields) ===
    // 카메라의 이름을 저장할 변수입니다.
    public String name;

    // === 생성자 (Constructors) ===
    // 생성자는 객체가 생성될 때 호출되어 필드를 초기화하는 특별한 메소드입니다.

    /**
     * [1] 기본 생성자 (Default Constructor)
     * 매개변수가 없는 생성자입니다.
     * 이 생성자가 호출되면, 'this("카메라")'를 통해 아래에 있는 매개변수 하나짜리 생성자를 호출합니다.
     * 이렇게 하면 중복 코드를 줄이고, 초기화 로직을 한 곳에서 관리할 수 있습니다.
     * 이를 '생성자 체이닝(Constructor Chaining)'이라고 합니다.
     */
    public Camera() {
        this("카메라"); // 매개변수 있는 생성자를 호출하여 name을 "카메라"로 초기화
    }

    /**
     * [2] 매개변수 있는 생성자
     * 카메라의 이름을 매개변수로 받아서 name 필드를 초기화하는 생성자입니다.
     *
     * 'protected' 접근 제어자:
     * 이 생성자는 'protected' 접근 제어자를 가집니다.
     * 이는 다음과 같은 의미를 가집니다:
     * - 같은 패키지(_05_Inheritance_camera) 내의 다른 클래스에서는 이 생성자를 호출할 수 있습니다.
     * - 다른 패키지에 있는 클래스에서는 이 Camera 클래스를 '상속받은 자식 클래스'에서만 이 생성자를 호출할 수 있습니다.
     *   (예: super(name)을 통해)
     * 일반적인 public 생성자와 달리, 외부에서 직접 객체 생성을 제한하고, 상속 관계에서만 특정 초기화를 허용할 때 유용합니다.
     */
    protected Camera(String name) {
        this.name = name; // 매개변수로 받은 name을 현재 객체의 name 필드에 할당
    }

    // === 메소드 (Methods) ===

    /**
     * 사진 촬영 기능을 수행하는 메소드입니다.
     * 카메라의 이름과 함께 "사진을 촬영합니다" 메시지를 출력합니다.
     */
    public void takePicture() {
        System.out.printf("%s : 사진을 촬영합니다%n", this.name);
    }

    /**
     * 동영상 녹화 기능을 수행하는 메소드입니다.
     * 카메라의 이름과 함께 "동영상을 녹화합니다" 메시지를 출력합니다.
     */
    public void recordVideo() {
        System.out.printf("%s : 동영상을 녹화합니다%n", this.name);
    }

    /**
     * 카메라의 주요 기능을 보여주는 메소드입니다.
     * 카메라의 이름과 함께 "사진 촬영, 동영상 녹화" 메시지를 출력합니다.
     * 이 메소드는 자식 클래스에서 오버라이딩하여 각 카메라의 특성을 보여줄 수 있습니다.
     */
    public void showMainFeature() {
        System.out.printf("%s의 주요 기능 : 사진 촬영, 동영상 녹화%n", this.name);
    }
}
package _01_Inheritance_book;

/**
 * 자, 이번에는 '자식 클래스'인 Comic 클래스를 살펴볼게요.
 * 'extends Book' 이 부분이 바로 상속을 선언하는 코드예요. 'extends'는 '확장하다'라는 뜻이죠?
 * 즉, Comic 클래스는 Book 클래스를 확장해서 만들어졌다, 다시 말해 Book의 모든 것을 물려받았다는 의미입니다.
 *
 * 이렇게 상속을 받으면, 우리는 Comic 클래스 안에 title이나 price 변수를 또 선언하지 않아도
 * 마치 자기 것처럼 바로 사용할 수 있게 돼요. 정말 편리하죠?
 *
 * 이제 부모에게 물려받은 기능에 더해서, 만화책만이 가지는 새로운 속성과 기능을 추가해 보겠습니다.
 */
// 'public class Comic extends Book' -> 'Comic'이라는 클래스는 'Book'이라는 클래스를 상속받습니다.
public class Comic extends Book {

    // === 필드 (Fields) ===
    // Book 클래스로부터 title, price를 물려받은 상태입니다.
    // 여기에 만화책만의 속성인 '작가'를 추가해 볼게요.
    String author; // 만화책의 작가 이름을 저장할 변수입니다.

    // === 메소드 (Methods) ===
    // Book 클래스로부터 info() 메소드를 물려받은 상태입니다.
    // 하지만 만화책은 '작가' 정보도 함께 보여주고 싶어요.
    // 이럴 때 '메소드 오버라이딩(Method Overriding)'을 사용합니다.

    /**
     * 메소드 오버라이딩(Method Overriding)이란?
     * 부모 클래스로부터 물려받은 메소드를 자식 클래스에서 똑같은 이름으로 다시 만드는(재정의하는) 것을 말해요.
     * 이렇게 하면 자식 클래스의 상황에 맞게 기능을 수정하거나 확장할 수 있습니다.
     *
     * 여기서 'super'라는 아주 중요한 키워드가 등장해요!
     * 'super'는 부모 클래스 그 자체를 가리키는 특별한 단어입니다.
     * 'super.info()'는 "부모 클래스에 있는 원래 info() 메소드를 먼저 실행해주세요!" 라는 뜻이에요.
     * 이렇게 부모의 기능을 재사용하면서, 자식의 새로운 기능을 덧붙일 수 있답니다.
     */
    void info() {
        // 먼저, 부모인 Book 클래스의 info() 메소드를 호출해서 "책 이름은 ~, 책 가격은 ~입니다."를 출력합니다.
        super.info();
        // 그 다음에, 자식인 Comic 클래스에만 있는 '작가' 정보를 추가로 출력합니다.
        System.out.println("이 만화책의 작가는 " + author + "입니다.");
    }
}

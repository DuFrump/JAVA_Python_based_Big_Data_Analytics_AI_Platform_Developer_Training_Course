package _01_Inheritance_book;

/**
 * 안녕하세요, 두프룸프님! JAVA 선생님 제미니입니다.
 * 우리 오늘 상속(Inheritance)이라는 아주 중요한 개념에 대해 배워볼 거예요.
 * 상속은 '부모'가 가진 것을 '자식'에게 물려주는 것처럼,
 * 하나의 클래스(부모 클래스)가 가진 특징(속성과 기능)을 다른 클래스(자식 클래스)가 그대로 물려받는 것을 의미해요.
 * 이렇게 하면 코드를 반복해서 작성할 필요가 없어지고, 더 체계적으로 관리할 수 있답니다.
 *
 * 이 Book 클래스는 모든 책들이 공통적으로 가질 '제목'과 '가격'이라는 속성,
 * 그리고 그 정보를 보여주는 'info'라는 기능을 가진 '부모 클래스' 역할을 할 거예요.
 * 앞으로 만들 '만화책(Comic)' 클래스가 이 Book 클래스를 상속받아서 어떻게 변하는지 지켜봐 주세요!
 */
public class Book {
    // === 필드 (Fields) ===
    // 필드는 객체의 '상태'나 '속성'을 저장하는 변수들이에요.
    // 예를 들어, '사람'이라는 객체는 '이름', '나이' 같은 속성을 가질 수 있겠죠?
    // Book 클래스는 '제목'과 '가격'이라는 두 가지 속성을 가집니다.

    String title; // 책의 제목을 저장할 변수입니다. String은 문자열을 의미해요.
    int price;    // 책의 가격을 저장할 변수입니다. int는 정수를 의미해요.

    // === 메소드 (Methods) ===
    // 메소드는 객체가 할 수 있는 '동작'이나 '기능'을 정의해요.
    // '사람' 객체는 '먹다', '걷다', '말하다' 같은 동작을 할 수 있는 것처럼요.

    /**
     * 이 info() 메소드는 책의 제목과 가격 정보를 정해진 형식에 맞춰 화면에 출력하는 기능을 해요.
     * printf는 'format'의 f를 따온 것으로, 형식을 지정해서 출력하고 싶을 때 사용해요.
     * %s는 문자열(String)이 들어올 자리, %d는 정수(decimal)가 들어올 자리를 의미한답니다.
     * %n은 줄바꿈을 해주는 기호예요.
     */
    void info() {
        System.out.printf("책 이름은 %s이고, 책 가격은 %d입니다.%n", title, price);
    }
}
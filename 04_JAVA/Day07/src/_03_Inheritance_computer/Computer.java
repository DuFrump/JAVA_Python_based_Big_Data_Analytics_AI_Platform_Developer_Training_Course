package _03_Inheritance_computer;

/**
 * 세 번째 예제에 오신 것을 환영합니다!
 * 이번에는 컴퓨터를 예시로 상속의 기본 개념을 다시 한번 다져볼 거예요.
 *
 * 이 Computer 클래스는 모든 컴퓨터가 공통적으로 가지고 있는 기본적인 기능,
 * 즉 '전원을 켜고 끄는' 기능을 정의하는 '부모 클래스' 역할을 합니다.
 *
 * 아주 간단한 클래스이지만, 이 클래스를 통해 자식 클래스가 부모의 기능을
 * 어떻게 물려받아 사용하는지 명확하게 보여줄 수 있습니다.
 */
public class Computer {
    // === 메소드 (Methods) ===
    // 메소드는 객체가 수행할 수 있는 '동작'을 정의합니다.

    /**
     * 컴퓨터의 전원을 켜는 기능을 수행하는 메소드입니다.
     * 이 메소드가 호출되면 "컴퓨터가 켜졌습니다."라는 메시지를 화면에 출력합니다.
     */
    void powerOn() {
        System.out.println("컴퓨터가 켜졌습니다.");
    }

    /**
     * 컴퓨터의 전원을 끄는 기능을 수행하는 메소드입니다.
     * 이 메소드가 호출되면 "컴퓨터가 꺼졌습니다."라는 메시지를 화면에 출력합니다.
     */
    void powerOff() {
        System.out.println("컴퓨터가 꺼졌습니다.");
    }
}
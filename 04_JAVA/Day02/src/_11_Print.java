/**
 * 자바에서 콘솔(화면)에 텍스트를 출력하는 두 가지 주요 메소드인
 * `System.out.println()`과 `System.out.print()`의 차이점을 배웁니다.
 * 이 두 메소드는 출력 후 줄바꿈을 하는지 안 하는지에서 큰 차이가 있습니다.
 */

public class _11_Print {
    public static void main(String[] args) {

        // ------------------- 1. System.out.println() -------------------
        // `println`의 `ln`은 "line"의 약자입니다.
        // 이 메소드는 괄호 안의 내용을 화면에 출력한 후, "자동으로 다음 줄로 커서를 이동"시킵니다.
        // 즉, 출력 후에는 항상 줄바꿈이 일어납니다.

        System.out.println("우하하하"); // "우하하하"를 출력하고 다음 줄로 이동
        System.out.println("무야호");   // "무야호"를 출력하고 다음 줄로 이동
        System.out.println("안녕하세요."); // "안녕하세요."를 출력하고 다음 줄로 이동

        System.out.println("--------------------------");

        // ------------------- 2. System.out.print() -------------------
        // `print` 메소드는 괄호 안의 내용을 화면에 출력하기만 하고, "줄을 바꾸지 않습니다."
        // 따라서 다음에 오는 출력은 바로 이어서 같은 줄에 나오게 됩니다.

        System.out.print("안녕 ");      // "안녕 "을 출력하고 커서는 그 자리에 그대로 있습니다.
        System.out.println("길동아?");  // 바로 이어서 "길동아?"를 출력하고 줄바꿈합니다.
        // 최종 출력 결과: 안녕 길동아?

        System.out.print("행복해 ");    // "행복해 "를 출력하고 커서는 그 자리에 그대로 있습니다.
        System.out.println("보이는구나."); // 바로 이어서 "보이는구나."를 출력하고 줄바꿈합니다.
        // 최종 출력 결과: 행복해 보이는구나.

        System.out.print("즐거워 ");    // "즐거워 "를 출력하고 커서는 그 자리에 그대로 있습니다.
        System.out.println("보이니 좋다."); // 바로 이어서 "보이니 좋다."를 출력하고 줄바꿈합니다.
        // 최종 출력 결과: 즐거워 보이니 좋다.

        System.out.print("잘 살아");     // "잘 살아"를 출력하고 커서는 그 자리에 그대로 있습니다.
        // 이 프로그램은 여기서 끝나므로, 마지막에 줄바꿈이 없어도 눈에 띄는 차이는 없습니다.
        // 하지만 만약 이 뒤에 다른 `print` 문이 있다면, "잘 살아" 뒤에 이어서 출력될 것입니다.
    }
}
/**
 * 자바의 연산자 중에서 "산술 연산자(Arithmetic Operator)"와
 * "대입 연산자(Assignment Operator)"에 대해 배웁니다.
 */

public class _15_Operator3 {
    public static void main(String[] args) {

        // ------------------- 1. 산술 연산자 (+, -, *, /, %) -------------------
        // 사칙연산과 나머지를 구하는 연산자입니다.

        int x = 100;
        int y = 200;
        double z = 3.14;

        System.out.println("--- 기본 산술 연산 ---");
        System.out.println("덧셈 (x + y): " + (x + y)); // 덧셈: 100 + 200 = 300
        System.out.println("뺄셈 (x - y): " + (x - y)); // 뺄셈: 100 - 200 = -100
        System.out.println("곱셈 (x * y): " + (x * y)); // 곱셈: 100 * 200 = 20000

        // [중요] 정수 나눗셈 (`/`): 정수와 정수의 나눗셈 결과는 항상 "정수(몫)"입니다.
        // 소수점 이하는 버려집니다. (반올림되지 않습니다!)
        System.out.println("정수 나눗셈 (x / y): " + (x / y)); // 100 / 200 = 0.5 이지만, 정수 몫인 0이 결과값
        System.out.println("정수 나눗셈 (5 / 2): " + (5 / 2)); // 5 / 2 = 2.5 이지만, 정수 몫인 2가 결과값

        // 나머지 연산자 (`%`): 나눗셈의 나머지를 구합니다.
        System.out.println("나머지 (x % y): " + (x % y)); // 100을 200으로 나눈 나머지: 100
        System.out.println("나머지 (5 % 2): " + (5 % 2)); // 5를 2로 나눈 나머지: 1

        // 다른 타입과의 연산: `int`와 `double`을 연산하면, `int`가 `double`로 자동 형변환됩니다.
        // (자동 형변환: 작은 타입이 큰 타입으로 변환되는 것은 안전합니다)
        System.out.println("int + double (y + z): " + (y + z)); // 200 (int) + 3.14 (double) -> 200.0 (double) + 3.14 (double) = 203.14

        // [주의] 연산 결과의 오버플로우(Overflow)
        // `int` 타입은 약 -21억에서 21억까지의 정수만 저장할 수 있습니다.
        // 이 범위를 넘어서는 계산 결과는 잘못된 값(쓰레기값)을 만듭니다. 이를 오버플로우라고 합니다.
        int result = 100000 * 100000; // 10만 * 10만 = 100억. int 범위를 넘어섭니다.
        System.out.println("int 오버플로우 결과 (10만 * 10만): " + result); // 예상과 다른 음수 값이 출력될 수 있습니다.

        // 해결 방법: 더 큰 범위를 가진 `long` 타입을 사용해야 합니다.
        // 숫자 뒤에 `L`을 붙여 `long` 타입임을 명시해야 합니다.
        long longResult = 100000L * 100000L;
        System.out.println("long 정상 결과 (10만 * 10만): " + longResult); // 10000000000 (100억)

        System.out.println("\n--- 2. 대입(복합 대입) 연산자 (+=, -=, *=, /=, %=) ---");
        // 산술 연산과 대입을 한 번에 수행하는 편리한 연산자입니다.
        // `a = a + b;` 를 `a += b;` 와 같이 줄여서 쓸 수 있습니다.

        x = 10; // x를 10으로 초기화
        y = 1;  // y를 1로 초기화

        System.out.println("초기 x: " + x + ", y: " + y);

        y += x; // y = y + x; 와 동일 -> y = 1 + 10 = 11
        System.out.println("y += x : " + y); // 11

        y -= x; // y = y - x; 와 동일 -> y = 11 - 10 = 1
        System.out.println("y -= x : " + y); // 1

        y += 20; // y = y + 20; 와 동일 -> y = 1 + 20 = 21
        System.out.println("y += 20 : " + y); // 21

        y *= x; // y = y * x; 와 동일 -> y = 21 * 10 = 210
        System.out.println("y *= x : " + y); // 210

        y %= x; // y = y % x; 와 동일 -> y = 210 % 10 = 0 (210을 10으로 나눈 나머지)
        System.out.println("y %= x : " + y); // 0

        System.out.println("\n--- 3. 정확한 나눗셈 결과 얻기 (실수) ---");
        // 정수 나눗셈은 몫만 반환하므로, 정확한 실수 결과를 얻으려면 형변환이 필요합니다.

        System.out.println("정수 나눗셈 (5 / 2): " + (5 / 2)); // 몫인 2가 나옴

        // [잘못된 형변환 예시]: `(float)(5 / 2)`
        // 괄호 안의 `(5 / 2)`가 먼저 계산되어 `2`가 됩니다. 그 후에 `(float)2`가 되어 `2.0`이 됩니다.
        // 즉, 이미 소수점 이하가 버려진 후에 형변환이 일어나므로 원하는 결과를 얻을 수 없습니다.
        System.out.println("잘못된 형변환 ((float)(5 / 2)): " + (float)(5 / 2)); // 2.0

        // [올바른 형변환 예시]: `(float)5 / 2` 또는 `5.0 / 2`
        // 두 피연산자 중 하나라도 실수 타입이면, 전체 연산이 실수 연산으로 수행됩니다.
        // `(float)5`는 `5.0f`가 되고, `5.0f / 2`는 `5.0f / 2.0f`가 되어 `2.5`가 됩니다.
        System.out.println("올바른 형변환 ((float)5 / 2): " + ((float)5 / 2)); // 2.5
        System.out.println("올바른 형변환 (5.0 / 2): " + (5.0 / 2)); // 2.5
    }
}
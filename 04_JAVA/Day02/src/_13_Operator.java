/**
 * 자바의 연산자(Operator) 중에서 "부호 연산자(Sign Operator)"에 대해 배웁니다.
 * 부호 연산자는 숫자 앞에 붙어 해당 숫자의 부호를 결정하거나 변경하는 역할을 합니다.
 * 마치 수학에서 숫자 앞에 붙는 + 또는 - 기호와 같습니다.
 */

public class _13_Operator {
    public static void main(String[] args) {

        // ------------------- 부호 연산자 (+, -) -------------------

        int x = 100;

        // 1. `+` 연산자 (단항 연산자)
        //    - 변수의 부호를 그대로 유지합니다.
        //    - 사실상 아무런 변화를 주지 않으므로, 코드에서는 거의 사용되지 않습니다.
        int plusX = +x; // x의 값 100을 그대로 plusX에 저장

        // 2. `-` 연산자 (단항 연산자)
        //    - 변수의 부호를 반대로 바꿉니다.
        //    - 양수는 음수로, 음수는 양수로 만듭니다.
        int minusX = -x; // x의 값 100을 -100으로 바꿔 minusX에 저장

        // [중요] 부호 연산자는 변수 `x`의 값 자체를 바꾸는 것이 아닙니다!
        // `x`의 값을 읽어와서 부호 연산을 수행한 "결과"를 새로운 변수에 저장하거나 출력하는 것입니다.
        // `x`라는 원본 변수의 값은 연산 후에도 변함없이 100으로 유지됩니다.

        System.out.println("원래 x 값: " + x);         // 출력: 100
        System.out.println("+x 결과: " + plusX);      // 출력: 100
        System.out.println("-x 결과: " + minusX);     // 출력: -100
        System.out.println("연산 후 x 값: " + x);     // 출력: 100 (x의 값은 여전히 100입니다!)

        System.out.println("--------------------------");

        // 실수 타입에도 동일하게 적용됩니다.
        double d = 1.11;
        double result = -d; // d의 값 1.11을 -1.11로 바꿔 result에 저장

        System.out.println("-d 결과: " + -d);         // 출력: -1.11
        System.out.println("result 값: " + result);   // 출력: -1.11
        System.out.println("연산 후 d 값: " + d);     // 출력: 1.11 (d의 값은 여전히 1.11입니다!)

        // [참고] 단항 연산자와 이항 연산자
        // - 단항 연산자: 피연산자(연산의 대상)가 하나인 연산자 (예: `+x`, `-x`, `++i`, `--j`)
        // - 이항 연산자: 피연산자가 두 개인 연산자 (예: `a + b`, `c - d`, `x * y`)
    }
}
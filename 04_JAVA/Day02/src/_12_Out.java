/**
 * `System.out.printf()` 메소드의 다양한 형식 지정자(format specifier) 옵션을 배웁니다.
 * `printf`는 단순히 값을 출력하는 것을 넘어, 출력되는 값의 형태, 정렬, 자릿수 등을
 * 세밀하게 제어할 수 있게 해줍니다.
 *
 * 형식 지정자의 일반적인 구조:
 * `%[플래그][폭][.정밀도]형식지정자`
 *
 * - `%`: 형식 지정자의 시작을 알립니다.
 * - `플래그` (선택 사항): 출력 방식을 변경합니다. (예: `0`, `-`, `+`, `,`)
 * - `폭` (선택 사항): 출력될 전체 공간의 너비를 지정합니다.
 * - `.정밀도` (선택 사항): 실수에서는 소수점 이하 자릿수, 문자열에서는 출력할 문자 수를 지정합니다.
 * - `형식지정자` (필수): 어떤 타입의 데이터를 출력할지 지정합니다. (예: `d`, `f`, `s`)
 */

public class _12_Out {
    public static void main(String[] args) {

        // `%n`: 플랫폼(OS)에 맞는 줄바꿈 문자를 출력합니다. `println`의 `ln`과 같은 효과를 냅니다.
        // `\n`도 줄바꿈이지만, `%n`은 운영체제에 따라 적절한 줄바꿈 문자를 사용하므로 더 권장됩니다.

        // ------------------- 정수형 출력 (`%d`) -------------------
        System.out.println("--------------정수형 출력---------------");

        // 기본 정수 출력: `%d`
        System.out.printf("기본 정수: %d%n", 123);
        System.out.printf("여러 정수: %d %d %d%n", 1, 2, 3);

        // [폭] 지정: `%[숫자]d` - 지정된 숫자만큼의 공간을 확보하고, 기본적으로 오른쪽 정렬합니다.
        System.out.printf("오른쪽 정렬 (6칸): %6d%n", 1234); // "  1234" (앞에 공백 2칸)
        System.out.printf("오른쪽 정렬 (6칸): %6d%n", 12);   // "    12" (앞에 공백 4칸)

        // [플래그 0] 지정: `%0[숫자]d` - 폭을 확보하고 남는 공간을 0으로 채웁니다.
        System.out.printf("0으로 채우기 (6칸): %06d%n", 1234); // "001234"

        // [플래그 +] 지정: `%+d` - 양수일 때도 부호(+)를 표시합니다.
        System.out.printf("양수 부호 표시: %+d%n", 1234);  // "+1234"
        System.out.printf("음수 부호 표시: %+d%n", -1234); // "-1234" (음수는 원래 부호 표시)

        // [플래그 ,] 지정: `%,d` - 3자리마다 콤마(,)를 표시합니다. (숫자를 읽기 쉽게 해줍니다)
        System.out.printf("콤마 표시: %,d%n", 300000000); // "300,000,000"

        // [플래그 -] 지정: `%-d` - 폭을 확보하고 왼쪽 정렬합니다.
        System.out.printf("왼쪽 정렬 (6칸): %-6d%n%n", 1234); // "1234  "


        // ------------------- 실수형 출력 (`%f`) -------------------
        System.out.println("--------------실수형 출력---------------");
        // Math.PI는 원주율(3.1415926535...)을 나타내는 상수입니다.

        // 기본 실수 출력: `%f` (기본적으로 소수점 이하 6자리까지 출력합니다)
        System.out.printf("기본 실수: %f%n", Math.PI); // "3.141593"

        // [.정밀도] 지정: `%.[숫자]f` - 소수점 이하 자릿수를 지정합니다. (지정된 자릿수에서 반올림됩니다)
        System.out.printf("소수점 2자리: %.2f%n", Math.PI); // "3.14"
        System.out.printf("소수점 3자리: %.3f%n", Math.PI); // "3.142" (셋째 자리에서 반올림)

        // [폭.정밀도] 지정: `%[폭].[정밀도]f` - 전체 폭과 소수점 자릿수를 함께 지정합니다.
        System.out.printf("전체 6칸, 소수점 2자리: %6.2f%n", Math.PI); // "  3.14"

        // [플래그 -] 지정: `%-f` - 왼쪽 정렬합니다.
        System.out.printf("왼쪽 정렬 (6칸, 소수점 2자리): %-6.2f%n", Math.PI); // "3.14  "

        // [플래그 0] 지정: `%0f` - 빈칸을 0으로 채웁니다.
        System.out.printf("0으로 채우기 (6칸, 소수점 2자리): %06.2f%n", Math.PI); // "03.14"

        // [플래그 +] 지정: `%+f` - 양수 부호(+)를 표시합니다.
        System.out.printf("양수 부호 표시 (6칸, 소수점 2자리): %+6.2f%n%n", Math.PI); // "+3.14"


        // ------------------- 문자열 출력 (`%s`) -------------------
        System.out.println("--------------문자열 출력---------------");

        // 기본 문자열 출력: `%s`
        System.out.printf("기본 문자열: %s%n", "JAVA");

        // [폭] 지정: `%[숫자]s` - 지정된 숫자만큼의 공간을 확보하고, 기본적으로 오른쪽 정렬합니다.
        System.out.printf("오른쪽 정렬 (6칸): %6s%n", "JAVA"); // "  JAVA"

        // [플래그 -] 지정: `%-s` - 왼쪽 정렬합니다.
        System.out.printf("왼쪽 정렬 (6칸): %-6s%n", "JAVA"); // "JAVA  "

        // [.정밀도] 지정: `%.[숫자]s` - 문자열의 앞에서부터 지정된 숫자만큼의 문자만 출력합니다.
        System.out.printf("문자열 자르기 (2글자): %.2s%n", "JAVA"); // "JA"

        // [폭.정밀도]와 [플래그 -] 조합
        System.out.printf("왼쪽 정렬 (6칸), 2글자: %-6.2s%n%n", "JAVA"); // "JA    "


        // ------------------- 응용 1: println 사용 시 표 만들기 -------------------
        System.out.println("--------------응용1: println 사용---------------");
        // `println`만으로는 표의 칸을 맞추기가 매우 어렵습니다. 각 데이터의 길이가 다르기 때문입니다.
        System.out.println("이름 영어 수학 평균");
        System.out.println("나루토 " + 90 + " " + 80 + " " + 85.0);
        System.out.println("사스케 " + 100 + " " + 100 + " " + 100.0);
        System.out.println("사쿠라 " + 95 + " " + 100 + " " + 97.5);


        // ------------------- 응용 2: printf 사용 시 표 만들기 -------------------
        System.out.printf("%n%n--------------응용2: printf 사용---------------%n");
        // `printf`를 사용하면 정렬된 표를 깔끔하게 만들 수 있습니다. 각 열의 폭을 지정하여 정렬합니다.
        // `%-6s`: 이름 (문자열, 6칸 확보, 왼쪽 정렬)
        // `%5s`: 영어 (문자열, 5칸 확보, 오른쪽 정렬)
        // `%5s`: 수학 (문자열, 5칸 확보, 오른쪽 정렬)
        // `%7s`: 평균 (문자열, 7칸 확보, 오른쪽 정렬)
        System.out.printf("%-6s %5s %5s %7s%n", "이름", "영어", "수학", "평균"); // 헤더 출력
        System.out.printf("%-6s %5d %5d %7.1f%n", "나루토", 90, 80, 85.0); // %7.1f: 전체 7칸, 소수점 1자리
        System.out.printf("%-6s %5d %5d %7.1f%n", "사스케", 100, 100, 100.0);
        System.out.printf("%-6s %5d %5d %7.1f%n", "사쿠라", 95, 100, 97.5);


        // ------------------- 참고: 글자 폭 (한글 vs 영문) -------------------
        System.out.printf("%n--------------참고: 글자 폭--------------%n");
        // 콘솔 환경 및 폰트에 따라 다를 수 있지만, 일반적으로:
        // - 영문, 숫자, 공백은 1칸(반각)을 차지합니다.
        System.out.println("ABCDEFG");
        System.out.println("abcdefg");
        // - 한글, 한자 등은 2칸(전각)을 차지하는 경우가 많습니다.
        //   printf로 폭을 지정할 때 이 점을 고려해야 정확한 정렬이 가능합니다.
        System.out.println("가나다라마바사");
        System.out.println("가 나 다 라"); // 띄어쓰기 포함 시 더 복잡해짐

        System.out.println("printf는 복잡한 출력을 깔끔하게 만들 때 매우 유용합니다!");
    }
}
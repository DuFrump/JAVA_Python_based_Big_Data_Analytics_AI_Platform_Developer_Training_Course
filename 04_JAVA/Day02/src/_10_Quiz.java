/**
 * 이번 퀴즈는 `Scanner`를 활용하여 사용자로부터 두 가지 정보를 입력받고,
 * 이를 조합하여 하나의 문장을 완성하는 연습입니다.
 * 특히 `next()`와 `nextLine()`을 함께 사용할 때의 주의사항을 복습하는 데 중점을 둡니다.
 */

import java.util.Scanner;

public class _10_Quiz {
    public static void main(String[] args) {
        // 1. Scanner 객체 생성: 사용자 입력을 받기 위한 준비 단계입니다.
        Scanner sc = new Scanner(System.in);

        // ------------------- 첫 번째 질문: 배우는 언어 입력받기 -------------------
        System.out.print("무슨 언어를 배우시나요? (예: Java) : ");
        // `sc.next()` 사용: 띄어쓰기(공백) 전까지의 한 단어만 읽어옵니다.
        // 예를 들어 "Java 프로그래밍"이라고 입력하면 "Java"만 `lang` 변수에 저장됩니다.
        String lang = sc.next();

        // [중요] `next()` 메소드 사용 후 `nextLine()`을 위한 버퍼 비우기
        // `sc.next()`는 입력된 단어만 가져가고, 사용자가 입력한 엔터(줄바꿈 문자 \n)는 입력 버퍼에 남겨둡니다.
        // 이 남아있는 엔터 때문에 다음에 `sc.nextLine()`을 호출하면, 이 엔터를 바로 읽어버려
        // 실제 사용자 입력을 받지 못하고 넘어가버리는 문제가 발생합니다.
        // 따라서, `sc.nextLine()`을 한 번 더 호출하여 버퍼에 남아있는 엔터를 "소비"해 주어야 합니다.
        sc.nextLine(); // 버퍼에 남아있는 엔터("\n")를 읽어서 버립니다.

        // ------------------- 두 번째 질문: 배운 소감 입력받기 -------------------
        System.out.print("\n배우시니 어떠신가요? (소감을 문장으로 입력) : ");
        // `sc.nextLine()` 사용: 띄어쓰기를 포함하여 사용자가 입력한 한 줄 전체를 읽어옵니다.
        // 위에서 `sc.nextLine()`으로 버퍼를 비워주었기 때문에, 이제 정상적으로 소감을 입력받을 수 있습니다.
        String exp = sc.nextLine();

        // ------------------- 최종 문장 출력 -------------------
        // 입력받은 언어(`lang`)와 소감(`exp`)을 조합하여 최종 문장을 출력합니다.
        System.out.printf("\n[%s]를 배우니 [%s]!%n", lang, exp);

        // 2. Scanner 자원 해제: 사용이 끝난 Scanner 객체를 닫아 시스템 자원을 반환합니다.
        sc.close();
    }
}
/**
 * 이번 퀴즈는 `Scanner`를 사용하여 사용자로부터 키를 입력받고,
 * 조건 연산자(삼항 연산자)를 활용하여 놀이기구 탑승 가능 여부를 판단하는 연습입니다.
 * 실제 놀이공원에서 키 제한이 있는 놀이기구를 타는 상황을 상상해 보세요!
 */

import java.util.Scanner;

public class _18_Quiz {
    public static void main(String[] args) {

        // 1. Scanner 객체 생성: 사용자로부터 키보드 입력을 받기 위한 필수 준비 단계입니다.
        Scanner sc = new Scanner(System.in);

        // 2. 사용자에게 키 입력 요청 메시지 출력
        // `print`를 사용하여 메시지 출력 후 커서가 같은 줄에 남아있도록 합니다.
        System.out.print("당신의 키는 몇 cm입니까? (예: 130.5) : ");

        // 3. 사용자로부터 키(실수)를 입력받아 `height` 변수에 저장
        // `sc.nextDouble()`: 사용자가 입력한 다음 "실수" 값을 읽어들입니다.
        double height = sc.nextDouble();

        // 4. 조건 연산자(삼항 연산자)를 사용하여 탑승 가능 여부 판단
        // 놀이기구 탑승 조건: 키가 120cm보다 커야 합니다.
        // `조건식 ? 값1(참일 때) : 값2(거짓일 때);`
        // - `조건식`: `height > 120` (사용자의 키가 120보다 큰가?)
        // - `값1` (참일 때): 조건식이 `true`이면 "탑승 가능하십니다." 문자열이 선택됩니다.
        // - `값2` (거짓일 때): 조건식이 `false`이면 "탑승 불가능하십니다." 문자열이 선택됩니다.
        String result = (height > 120) ? "탑승 가능하십니다." : "탑승 불가능하십니다.";

        // 5. 판단 결과 출력
        System.out.println(result);

        // 6. Scanner 자원 해제: 사용이 끝난 Scanner 객체를 닫아 시스템 자원을 효율적으로 관리합니다.
        sc.close();
    }
}
/**
 * 문자(char) 데이터 타입에 대해 배웁니다.
 * char는 단 하나의 문자(글자)를 저장하기 위한 타입이며, 작은따옴표('')로 값을 감쌉니다.
 * 예를 들어, 'A', '가', '!' 와 같은 한 글자를 저장할 때 사용합니다.
 */
public class _05_Char {
    public static void main(String[] args) {

        // ------------------- char 타입의 기본 사용 -------------------

        // char 타입 변수에 각각 한글 '가'와 영문 'A'를 저장합니다.
        char ga = '가'; // '가'라는 한 글자를 변수 ga에 저장
        char a = 'A';   // 'A'라는 한 글자를 변수 a에 저장

        // char 변수를 직접 출력하면 저장된 문자가 그대로 화면에 나타납니다.
        System.out.println("변수 ga에 저장된 문자: " + ga); // 출력: 가
        System.out.println("변수 a에 저장된 문자: " + a);  // 출력: A

        System.out.println("--------------------------------");

        // ------------------- 문자의 유니코드(Unicode) 값 이해하기 -------------------
        // 컴퓨터는 문자를 직접 이해하지 못하고, 모든 것을 숫자로 변환하여 처리합니다.
        // 그래서 각 문자에는 고유한 숫자(코드)가 부여되어 있습니다. 이 표준 코드 체계를 '유니코드(Unicode)'라고 합니다.
        // char 타입의 값을 int 타입 변수에 저장하면, 해당 문자의 유니코드 숫자 값이 저장됩니다.

        // 예시: '나'와 'B'의 유니코드 값 확인
        int naUnicode = '나'; // '나' 문자의 유니코드 값을 정수형 변수 naUnicode에 저장
        int bUnicode = 'B';   // 'B' 문자의 유니코드 값을 정수형 변수 bUnicode에 저장

        // int 변수를 출력하면 문자가 아닌, 해당 문자의 유니코드 숫자 값이 출력됩니다.
        System.out.println("'나'의 유니코드 값: " + naUnicode); // 출력: 45208 (한글 '나'의 유니코드 값)
        System.out.println("'B'의 유니코드 값: " + bUnicode);  // 출력: 66 (영문 'B'의 유니코드 값, 아스키 코드와 동일)

        // [참고] 유니코드와 아스키 코드
        // 아스키 코드(ASCII)는 영문 알파벳, 숫자, 특수문자 등을 표현하는 128개의 코드입니다.
        // 유니코드(Unicode)는 전 세계의 모든 문자를 표현하기 위한 표준으로, 아스키 코드를 포함합니다.
        // 따라서 영문 'A'~'Z', 'a'~'z', '0'~'9' 등의 문자는 아스키 코드 값과 유니코드 값이 같습니다.
    }
}
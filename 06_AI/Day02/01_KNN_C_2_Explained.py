# [선생님] 안녕하세요! AI 머신러닝의 세계에 온 걸 환영해요.
# 오늘은 컴퓨터에게 '도미'와 '빙어'를 구별하는 법을 가르쳐 볼 거예요.
# 그러려면 먼저, 물고기들의 '길이'와 '무게' 데이터가 필요하답니다.

# 1. 데이터 준비: 물고기들의 신체검사 기록부
# --------------------------------------------------------------------
# 도미 35마리와 빙어 14마리의 길이와 무게를 각각 리스트에 담았어요.
# 마치 학생들의 키와 몸무게를 기록한 것처럼요.
fish_length = [25.4, 26.3, 26.5, 29.0, 29.0, 29.7, 29.7, 30.0, 30.0, 30.7, 31.0, 31.0,
               31.5, 32.0, 32.0, 32.0, 33.0, 33.0, 33.5, 33.5, 34.0, 34.0, 34.5, 35.0,
               35.0, 35.0, 35.0, 36.0, 36.0, 37.0, 38.5, 38.5, 39.5, 41.0, 41.0, 9.8,
               10.5, 10.6, 11.0, 11.2, 11.3, 11.8, 11.8, 12.0, 12.2, 12.4, 13.0, 14.3, 15.0]
fish_weight = [242.0, 290.0, 340.0, 363.0, 430.0, 450.0, 500.0, 390.0, 450.0, 500.0, 475.0, 500.0,
               500.0, 340.0, 600.0, 600.0, 700.0, 700.0, 610.0, 650.0, 575.0, 685.0, 620.0, 680.0,
               700.0, 725.0, 720.0, 714.0, 850.0, 1000.0, 920.0, 955.0, 925.0, 975.0, 950.0, 6.7,
               7.5, 7.0, 9.7, 9.8, 8.7, 10.0, 9.9, 9.8, 12.2, 13.4, 12.2, 19.7, 19.9]

# 2. 데이터 가공: 컴퓨터가 알아보기 쉽게 '문제집'과 '정답지' 만들기
# --------------------------------------------------------------------
# 컴퓨터는 [길이, 무게]처럼 짝지어진 데이터를 좋아해요.
# zip() 함수로 길이와 무게를 짝지어 'fish_data'라는 '문제집'을 만들어요.
fish_data = [[l, w] for l, w in zip(fish_length, fish_weight)]

# 이제 '정답지'를 만들 차례예요.
# 도미는 '1', 빙어는 '0'이라고 약속하고, 순서에 맞게 정답을 적어줘요.
# 도미 35마리(1이 35개), 빙어 14마리(0이 14개)
fish_target = [1]*35 + [0]*14

# 3. 잘못된 공부 방법: 편식하며 공부하기 (샘플링 편향)
# --------------------------------------------------------------------
# 만약 AI에게 도미 데이터로만 공부시키고, 빙어 데이터로 시험을 보면 어떻게 될까요?
# 앞에서부터 35개(전부 도미)는 공부용(train), 뒤에 14개(전부 빙어)는 시험용(test)으로 나눠볼게요.
# 이렇게 한 종류의 데이터만 쏠려서 들어가는 것을 '샘플링 편향'이라고 불러요. 아주 나쁜 공부 습관이죠!
print("--- [나쁜 예] 편식해서 공부한 경우 ---")
train_input_bad = fish_data[:35]    # 공부 자료: 도미 사진만 35장
train_target_bad = fish_target[:35] # 공부 정답: 전부 "도미"

test_input_bad = fish_data[35:]     # 시험 문제: 빙어 사진만 14장
test_target_bad = fish_target[35:]  # 시험 정답: 전부 "빙어"

# K-최근접 이웃(KNeighborsClassifier)이라는 AI 모델을 불러와요.
# 이 친구는 주변에 자기랑 비슷한 친구들을 보고 정체를 파악하는 똑똑한 탐정이에요.
from sklearn.neighbors import KNeighborsClassifier
kn = KNeighborsClassifier()

# 자, 이제 '도미'만으로 열심히 공부(학습)합니다.
kn.fit(train_input_bad, train_target_bad)

# 그리고 한 번도 본 적 없는 '빙어'로 시험을 봅니다. 과연 점수는?
score = kn.score(test_input_bad, test_target_bad)
print(f"시험 점수: {score}점 (땡! 하나도 못 맞췄어요!)\n")
# 결과는 0점! AI는 도미만 봐서 빙어를 전혀 모르기 때문이에요.

# 4. 올바른 공부 방법: 골고루 섞어서 공부하기
# --------------------------------------------------------------------
# 좋은 AI를 만들려면 '공부 자료'와 '시험 문제'에 도미와 빙어가 골고루 섞여 있어야 해요.
# 'numpy'라는 마법 도구를 사용하면 데이터를 쉽게 섞을 수 있어요.
import numpy as np

# 파이썬 리스트를 더 강력한 numpy 배열(array)로 변신!
input_arr = np.array(fish_data)
target_arr = np.array(fish_target)

# 데이터를 섞기 전에, '랜덤 시드'라는 것을 설정할 거예요.
# np.random.seed(42)는 "앞으로 무작위로 섞을 때, 항상 똑같은 순서로 섞어줘!"라는 약속이에요.
# 이렇게 하면 언제 코드를 실행해도 똑같은 결과를 얻을 수 있어서 실험할 때 아주 중요해요.
np.random.seed(42)

# 0부터 48까지(물고기 49마리) 번호표를 만들어요.
index = np.arange(49)
# 이제 이 번호표를 마구 섞어줍니다!
np.random.shuffle(index)

# 섞인 번호표 순서대로 물고기들을 다시 줄 세워요.
# 그리고 35마리는 공부용(train), 14마리는 시험용(test)으로 나눕니다.
# 이제 공부 자료와 시험 문제에 도미와 빙어가 골고루 섞여 있겠죠?
train_input = input_arr[index[:35]]
train_target = target_arr[index[:35]]

test_input = input_arr[index[35:]]
test_target = target_arr[index[35:]]

# 5. 확인: 정말 잘 섞였는지 눈으로 보자!
# --------------------------------------------------------------------
# 'matplotlib'이라는 도구로 데이터를 점으로 찍어(그래프) 확인해볼게요.
import matplotlib.pyplot as plt

# 파란색 점은 공부용(train), 주황색 점은 시험용(test) 데이터예요.
# 두 색깔이 전체적으로 잘 섞여 있는 게 보이죠? 이러면 성공이에요!
plt.scatter(train_input[:, 0], train_input[:, 1], label='Train set')
plt.scatter(test_input[:, 0], test_input[:, 1], label='Test set')
plt.xlabel('length (cm)')
plt.ylabel('weight (g)')
plt.legend() # 어떤 색이 무엇인지 알려주는 범례 표시
plt.title("Train/Test Data Distribution")
plt.show()

# 6. 최종 학습 및 시험: 골고루 공부한 AI의 실력은?
# --------------------------------------------------------------------
print("\n--- [좋은 예] 골고루 섞어서 공부한 경우 ---")
# 이제 잘 섞인 데이터로 다시 AI를 학습시킵니다.
kn.fit(train_input, train_target)

# 그리고 시험을 봅니다.
score = kn.score(test_input, test_target)
print(f"시험 점수: {score}점 (와! 100점 만점이에요!)")

# AI가 시험 문제를 어떻게 풀었는지 볼까요?
print("\nAI의 예측 답안:", kn.predict(test_input))
print("실제 정답지:", test_target)
# 예측과 정답이 완전히 똑같네요! 정말 똑똑해졌어요.


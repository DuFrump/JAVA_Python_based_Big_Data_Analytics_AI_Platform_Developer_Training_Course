# [설명] 
# ------------------------------------------------------------------------------------
# AI 머신러닝의 첫 단계는 '데이터'를 준비하는 것입니다.
# 여기서는 '도미'라는 물고기의 길이와 무게 데이터를 각각 리스트 형태로 준비합니다.
# 'bream_length'는 도미 35마리의 길이를, 'bream_weight'는 그에 해당하는 무게를 담고 있습니다.
# ------------------------------------------------------------------------------------
# 도미 데이터
bream_length = [25.4, 26.3, 26.5, 29.0, 29.0, 29.7, 29.7, 30.0, 30.0, 30.7, 31.0, 31.0, 31.5, 32.0, 32.0, 32.0, 33.0, 33.0, 33.5, 33.5, 34.0, 34.0, 34.5, 35.0, 35.0, 35.0, 35.0, 36.0, 36.0, 37.0, 38.5, 38.5, 39.5, 41.0, 41.0]
bream_weight = [242.0, 290.0, 340.0, 363.0, 430.0, 450.0, 500.0, 390.0, 450.0, 500.0, 475.0, 500.0, 500.0, 340.0, 600.0, 600.0, 700.0, 700.0, 610.0, 650.0, 575.0, 685.0, 620.0, 680.0, 700.0, 725.0, 720.0, 714.0, 850.0, 1000.0, 920.0, 955.0, 925.0, 975.0, 950.0]

# [설명]
# ------------------------------------------------------------------------------------
# 데이터를 눈으로 직접 확인하는 것은 매우 중요합니다. 'matplotlib'이라는 라이브러리를 사용하면
# 데이터를 그래프(시각화)로 쉽게 표현할 수 있습니다.
# ------------------------------------------------------------------------------------
import matplotlib.pyplot as plt

# [설명]
# ------------------------------------------------------------------------------------
# scatter 함수는 점을 찍어주는 함수입니다. x축을 길이(length), y축을 무게(weight)로 해서
# 도미 데이터가 좌표 평면에 어떻게 분포하는지 점으로 찍어보는 과정입니다.
# 이렇게 하면 '길이가 길수록 무게도 많이 나가는구나' 같은 데이터의 경향을 파악할 수 있습니다.
# ------------------------------------------------------------------------------------
plt.scatter(bream_length, bream_weight)
plt.xlabel('length') # x축 이름
plt.ylabel('weight') # y축 이름
plt.show() # 그래프를 화면에 보여줌

# [설명]
# ------------------------------------------------------------------------------------
# 이제 비교 대상인 '빙어' 데이터를 준비합니다. (코드에서는 방어로 표현되었네요)
# 빙어 14마리의 길이와 무게 데이터입니다.
# ------------------------------------------------------------------------------------
# 방어 데이터
smelt_length = [9.8, 10.5, 10.6, 11.0, 11.2, 11.3, 11.8, 11.8, 12.0, 12.2, 12.4, 13.0, 14.3, 15.0]
smelt_weight = [6.7, 7.5, 7.0, 9.7, 9.8, 8.7, 10.0, 9.9, 9.8, 12.2, 13.4, 12.2, 19.7, 19.9]

# [설명]
# ------------------------------------------------------------------------------------
# 빙어 데이터도 도미와 마찬가지로 그래프에 점으로 찍어 분포를 확인합니다.
# 도미와 빙어의 점들이 서로 다른 위치에 그룹지어 나타나는 것을 확인할 수 있을 거예요.
# ------------------------------------------------------------------------------------
plt.scatter(smelt_length, smelt_weight)
plt.xlabel('length')
plt.ylabel('weight')
plt.show()

# [설명]
# ------------------------------------------------------------------------------------
# 이제 머신러닝 모델을 '학습'시키기 위해, 두 물고기 데이터를 하나로 합칩니다.
# 도미 길이 리스트와 빙어 길이 리스트를 더해서 하나의 전체 길이 리스트를 만듭니다.
# ------------------------------------------------------------------------------------
length = bream_length + smelt_length
weight = bream_weight + smelt_weight

# [설명]
# ------------------------------------------------------------------------------------
# scikit-learn(사이킷런)이라는 머신러닝 라이브러리는 [특성1, 특성2] 형태의 2차원 리스트를
# 입력 데이터로 주로 사용합니다.
# zip 함수를 이용해 length와 weight를 짝지어 [길이, 무게] 형태의 리스트로 만듭니다.
# 이것이 바로 모델에게 알려줄 '문제지' (입력 데이터) 입니다.
# ------------------------------------------------------------------------------------
fish_data = [[l, w] for l, w in zip(length, weight)]

# 인풋 데이터
print("인풋 데이터 확인")
print(fish_data)
print()

# [설명]
# ------------------------------------------------------------------------------------
# '문제지'가 있으면 '정답지'도 있어야겠죠?
# fish_data의 각 데이터가 어떤 물고기인지 알려주는 '정답' 리스트를 만듭니다.
# 여기서는 도미를 1, 빙어를 0으로 정했습니다. (이것을 '레이블' 또는 '타겟'이라고 부릅니다)
# 도미 데이터가 35개, 빙어 데이터가 14개이므로 1을 35번, 0을 14번 반복해서 리스트를 만듭니다.
# ※ 참고: 기존 주석 '# 1 방어 / 0 도미'는 코드와 반대로 되어있습니다.
#   코드를 보면 35개인 도미(bream)가 1, 14개인 빙어(smelt)가 0으로 지정되었습니다.
# ------------------------------------------------------------------------------------
# 타겟 데이터
# 1 방어 / 0 도미
fish_target = [1]*35 + [0]*14
print(fish_target)
print()

# [설명]
# ------------------------------------------------------------------------------------
# 이제 본격적으로 머신러닝 모델을 사용할 시간입니다.
# 사이킷런 라이브러리에서 K-최근접 이웃 '분류' 모델(KNeighborsClassifier)을 가져옵니다.
# ------------------------------------------------------------------------------------
# k-최근접 이웃 알고리즘 학습
# KNN (K-Nearest Neighbors)
# K - 근처 몇개의 이웃을 참고하지 (K 개)
from sklearn.neighbors import KNeighborsClassifier

# [설명]
# ------------------------------------------------------------------------------------
# 가져온 모델을 kn이라는 변수에 담아 생성합니다. 이제 kn이 KNN 모델 그 자체입니다.
# ------------------------------------------------------------------------------------
kn = KNeighborsClassifier()

# [설명]
# ------------------------------------------------------------------------------------
# 모델을 '학습(training)' 시킵니다. fit() 함수에 '문제지(fish_data)'와 '정답지(fish_target)'를
# 함께 넣어주면 모델이 데이터와 정답의 관계를 학습합니다.
# KNN 모델의 경우, 사실 이 과정은 그냥 데이터를 통째로 저장하는 것과 같습니다.
# ------------------------------------------------------------------------------------
# KNN 분류 학습
kn.fit(fish_data, fish_target)
print('kn 모델변수에 학습 완료')
print()

# [설명]
# ------------------------------------------------------------------------------------
# 이제 모델이 잘 학습되었는지, 그리고 새로운 데이터는 어떻게 예측할지 시각적으로 확인해봅시다.
# 도미(파란색 점)와 빙어(주황색 점)를 한 그래프에 모두 그립니다.
# 그리고 우리가 정체를 모르는 새로운 물고기(길이 30, 무게 600)를 삼각형(^)으로 표시해봅니다.
# 눈으로 보기에도 삼각형은 파란색 점(도미) 그룹에 더 가까워 보이죠?
# ------------------------------------------------------------------------------------
# 방어와 도미 그래프
plt.scatter(bream_length, bream_weight)
plt.scatter(smelt_length, smelt_weight)
plt.scatter(30, 600, marker='^') # 새로운 물고기 데이터
plt.xlabel('length')
plt.ylabel('weight')
plt.show()

# [설명]
# ------------------------------------------------------------------------------------
# 이제 모델에게 직접 물어볼 차례입니다. predict() 함수에 새로운 물고기의 데이터 [[30, 600]]을
# 넣어서 어떤 물고기일지 예측해달라고 요청합니다.
# 예측 결과로 [1]이 나왔다면, 모델은 이 물고기를 '도미'라고 판단한 것입니다.
# ------------------------------------------------------------------------------------
print('예측 결과')
print(kn.predict([[30, 600]]))
print()

# [설명]
# ------------------------------------------------------------------------------------
# KNN 모델은 어떻게 예측을 할까요? 바로 학습할 때 받은 모든 데이터를 저장해두고,
# 새로운 데이터가 들어오면 모든 점들과의 거리를 계산합니다.
# 그리고 가장 가까운 K개의 이웃을 보고 다수결로 정체를 결정합니다.
# 그래서 KNN은 '게으른 학습(Lazy Learning)'이라고도 불립니다.
# ------------------------------------------------------------------------------------
# KNN - 모든 점의 거리를 다 계산해서 가장 가까운 5개의 이웃을 보고 분류 
# 모든 데이터의 정보를 가지고 있음
# 사실상 훈련이라고 하기엔 모호함.

# [설명]
# ------------------------------------------------------------------------------------
# 모델(kn)이 학습 데이터(문제지)를 어떻게 저장하고 있는지 직접 확인해볼 수 있습니다.
# _fit_X 속성에는 입력 데이터(fish_data)가 그대로 저장되어 있습니다.
# ------------------------------------------------------------------------------------
print(kn._fit_X)
print()

# [설명]
# ------------------------------------------------------------------------------------
# _y 속성에는 정답 데이터(fish_target)가 그대로 저장되어 있습니다.
# ------------------------------------------------------------------------------------
print(kn._y)
print()

# [설명]
# ------------------------------------------------------------------------------------
# KNeighborsClassifier()를 만들 때 아무런 옵션을 주지 않으면,
# 기본적으로 이웃의 수(K)는 5로 설정됩니다.
# 만약 이 K값을 49(전체 데이터 수)로 설정하면 어떻게 될까요?
# ------------------------------------------------------------------------------------
# 디폴트 이웃수 5개
# K를 49개로 바꿔 보면??

# [설명]
# ------------------------------------------------------------------------------------
# n_neighbors=49 라는 옵션을 주어 K가 49인 새로운 KNN 모델을 만듭니다.
# ------------------------------------------------------------------------------------
kn49 = KNeighborsClassifier(n_neighbors=49)

# [설명]
# ------------------------------------------------------------------------------------
# 이 모델도 똑같이 학습시킵니다. (데이터를 저장합니다)
# ------------------------------------------------------------------------------------
kn49.fit(fish_data, fish_target)

# [설명]
# ------------------------------------------------------------------------------------
# score() 함수는 모델의 '정확도'를 평가하는 함수입니다.
# 학습에 사용했던 데이터를 그대로 넣어서 "얼마나 잘 맞추는지" 점수를 매겨봅니다.
# 결과 = (맞춘 개수) / (전체 데이터 개수)
# K=49로 설정하면, 어떤 데이터를 예측하든 전체 49개 데이터를 모두 참고하게 됩니다.
# 우리 데이터는 도미(1)가 35마리, 빙어(0)가 14마리이므로, 무조건 다수인 도미(1)로만 예측하게 됩니다.
# 따라서 전체 49개 중 도미 35개만 맞추게 되므로, 정확도는 35/49가 됩니다.
# ------------------------------------------------------------------------------------
# 분류 모델에서 score는 맞춘수/전체
print(kn49.score(fish_data, fish_target))

print(35/49)
print()


